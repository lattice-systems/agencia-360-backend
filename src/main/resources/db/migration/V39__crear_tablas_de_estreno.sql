-- M16 Estreno (V2-M16.01 a V2-M16.04): solicitudes de prueba de manejo y de
-- cotización que hace el cliente desde la app, y los parámetros con que se
-- calcula la mensualidad estimada. El prospecto lo crea ventascrm por evento.

create table parametro_financiamiento (
    id                  bigint generated by default as identity primary key,
    tasa_anual          numeric(6, 4) not null,
    enganche_minimo_pct numeric(5, 4) not null,
    plazos              varchar(60)   not null,
    updated_at          timestamp(6) with time zone not null default now(),
    constraint ck_parametro_financiamiento_tasa check (tasa_anual > 0 and tasa_anual < 1),
    constraint ck_parametro_financiamiento_enganche check (enganche_minimo_pct >= 0 and enganche_minimo_pct < 1)
);


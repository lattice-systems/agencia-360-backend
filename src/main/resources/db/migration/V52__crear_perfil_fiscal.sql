-- V2-M08.05: datos fiscales del cliente para facturar sus servicios (tabla
-- perfil_fiscal de la ficha, sección 8). La facturación es simulada (ADR 0009),
-- pero los datos siguen las reglas de CFDI 4.0. El RFC y la razón social se
-- guardan en mayúsculas; el régimen y el uso son claves de los catálogos del SAT
-- que valida la aplicación. Un cliente tiene a lo más un predeterminado.

create table perfil_fiscal (
    id             bigint generated by default as identity primary key,
    cliente_id     bigint       not null references cliente (id),
    rfc            varchar(13)  not null,
    razon_social   varchar(254) not null,
    regimen_fiscal varchar(3)   not null,
    codigo_postal  varchar(5)   not null,
    uso_cfdi       varchar(4)   not null,
    correo         varchar(254),
    predeterminado boolean      not null default false,
    creado_en      timestamp(6) with time zone not null default now(),
    actualizado_en timestamp(6) with time zone not null default now(),
    constraint ck_perfil_fiscal_rfc check (rfc ~ '^[A-ZÑ&]{3,4}[0-9]{6}[A-Z0-9]{2}[0-9A]$'),
    constraint ck_perfil_fiscal_codigo_postal check (codigo_postal ~ '^[0-9]{5}$'),
    constraint ck_perfil_fiscal_regimen check (regimen_fiscal ~ '^[0-9]{3}$'),
    constraint ck_perfil_fiscal_razon_social check (length(btrim(razon_social)) > 0)
);

create index ix_perfil_fiscal_cliente on perfil_fiscal (cliente_id, id);

create unique index uq_perfil_fiscal_predeterminado on perfil_fiscal (cliente_id) where predeterminado;

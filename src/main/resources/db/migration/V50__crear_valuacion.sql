-- V2-M26 · Valuación formal y toma a cuenta (tabla de la ficha, sección 22).
--
-- De la ficha: id, estimacion_toma_cuenta_id, cliente_id, fotos, cita_id,
-- oferta, vigencia_hasta y estado. El resto son campos agregados.
-- fotos es un objeto JSON de toma a {"clave", "subidaEn"}, guardado como texto
-- igual que estimacion_toma_cuenta.supuestos.
create table valuacion (
    id                        bigint generated by default as identity primary key,
    estimacion_toma_cuenta_id bigint       not null,
    cliente_id                bigint       not null,
    fotos                     text         not null default '{}',
    cita_id                   bigint,
    oferta                    numeric(12, 2),
    vigencia_hasta            date,
    estado                    varchar(15)  not null,
    vehiculo_cliente_id       bigint       not null,
    prospecto_id              bigint,
    oferta_nota               varchar(500),
    ofertada_por              bigint,
    ofertada_en               timestamp(6) with time zone,
    respondida_en             timestamp(6) with time zone,
    created_at                timestamp(6) with time zone not null,
    updated_at                timestamp(6) with time zone not null,
    constraint fk_valuacion_estimacion foreign key (estimacion_toma_cuenta_id) references estimacion_toma_cuenta (id),
    constraint fk_valuacion_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_valuacion_cita foreign key (cita_id) references cita (id),
    constraint fk_valuacion_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint fk_valuacion_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint ck_valuacion_estado check (estado in
        ('SOLICITADA', 'CITA_AGENDADA', 'OFERTADA', 'ACEPTADA', 'RECHAZADA', 'VENCIDA')),
    constraint ck_valuacion_oferta check (oferta is null or oferta > 0),
    constraint ck_valuacion_vigencia check ((oferta is null) = (vigencia_hasta is null)),
    constraint ck_valuacion_con_oferta check
        (estado not in ('OFERTADA', 'ACEPTADA', 'RECHAZADA', 'VENCIDA') or oferta is not null),
    constraint ck_valuacion_con_cita check (estado <> 'CITA_AGENDADA' or cita_id is not null)
);

create index ix_valuacion_cliente on valuacion (cliente_id, created_at desc);

-- Una sola valuación abierta por cliente y vehículo. Incluye al cliente para
-- que un vehículo que cambia de dueño no quede bloqueado por la del anterior.
create unique index uq_valuacion_abierta on valuacion (cliente_id, vehiculo_cliente_id)
    where estado in ('SOLICITADA', 'CITA_AGENDADA', 'OFERTADA');

-- Una cita puede ser la inspección de una valuación (motivo VALUACION).
alter table cita drop constraint ck_cita_motivo;
alter table cita add constraint ck_cita_motivo check
    (motivo is null or motivo in
        ('MANTENIMIENTO', 'REPARACION', 'REVISION', 'GARANTIA', 'CAMPANA', 'VALUACION', 'OTRO'));

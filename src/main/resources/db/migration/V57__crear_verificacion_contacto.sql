-- V2-M01.07: confirmar el correo (y algún día el teléfono) antes de guardarlo.
--
-- El dato nuevo vive aquí mientras se verifica, no en `cliente`. Guardarlo
-- antes de confirmarlo dejaría al cliente con un correo que no ha probado que
-- es suyo y, como `cuenta_app.usuario` sigue al correo (V2-T05.03), **sin poder
-- entrar**.
--
-- `TELEFONO` entra en el check desde ahora aunque nadie lo emita todavía:
-- verificarlo exige mandar un código por SMS y no hay con qué. Así, cuando el
-- equipo decida el proveedor, esa mitad no necesita otra migración.
create table verificacion_contacto (
    id          bigint generated by default as identity primary key,
    cliente_id  bigint       not null,
    tipo        varchar(10)  not null,
    valor_nuevo varchar(120) not null,
    -- BCrypt, igual que codigo_recuperacion: el código no se guarda en claro.
    codigo_hash varchar(100) not null,
    expira      timestamp(6) with time zone not null,
    usado       boolean      not null default false,
    usado_en    timestamp(6) with time zone,
    intentos    integer      not null default 0,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint fk_verificacion_contacto_cliente foreign key (cliente_id) references cliente (id),
    constraint ck_verificacion_contacto_tipo check (tipo in ('CORREO', 'TELEFONO')),
    constraint ck_verificacion_contacto_intentos check (intentos >= 0)
);

-- Se busca por cliente y se descartan las usadas o vencidas.
create index idx_verificacion_contacto_cliente on verificacion_contacto (cliente_id, usado);

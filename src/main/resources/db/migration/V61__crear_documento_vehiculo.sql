-- V2-M09.01: documentos del vehículo (ficha técnica, sección 9).
--
-- Los campos de la ficha se respetan tal cual: id, vehiculo_cliente_id, tipo,
-- archivo_url, vence_en, origen y creado_en. Campos añadidos (R1 permite
-- agregar): `titulo` (nombre libre, obligatorio con tipo OTRO), `numero` (folio
-- o número de póliza), `emitido_en`, y `aseguradora` y `telefono_aseguradora`
-- (solo la póliza; V2-M11.02 los usa para llamar a la aseguradora).
--
-- `archivo_url` es opcional: V2-M09.02 sube el archivo; hasta entonces el
-- documento existe solo como registro con sus fechas. El estado (vigente, por
-- vencer, vencido) no se guarda: se calcula al consultar.
create table documento_vehiculo (
    id                   bigint generated by default as identity primary key,
    vehiculo_cliente_id  bigint       not null,
    tipo                 varchar(30)  not null,
    titulo               varchar(80),
    numero               varchar(60),
    emitido_en           date,
    vence_en             date,
    archivo_url          varchar(500),
    origen               varchar(10)  not null default 'CLIENTE',
    aseguradora          varchar(80),
    telefono_aseguradora varchar(30),
    creado_en            timestamp(6) with time zone not null default now(),
    constraint fk_documento_vehiculo_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint ck_documento_vehiculo_tipo check (tipo in ('POLIZA', 'TARJETA_CIRCULACION', 'VERIFICACION',
        'TENENCIA', 'LICENCIA', 'GARANTIA', 'FACTURA', 'OTRO')),
    constraint ck_documento_vehiculo_origen check (origen in ('CLIENTE', 'AGENCIA')),
    constraint ck_documento_vehiculo_titulo_otro check (tipo <> 'OTRO' or titulo is not null),
    constraint ck_documento_vehiculo_fechas check (emitido_en is null or vence_en is null or vence_en >= emitido_en)
);

create index ix_documento_vehiculo_vehiculo on documento_vehiculo (vehiculo_cliente_id, vence_en);


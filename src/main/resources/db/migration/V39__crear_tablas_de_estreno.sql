create table solicitud_estreno (
    id                         bigint generated by default as identity primary key,
    cliente_id                 bigint        not null,
    modelo_catalogo_id         bigint        not null,
    tipo                       varchar(20)   not null,
    preferencia_fecha          date,
    preferencia_franja         varchar(10),
    enganche                   numeric(12, 2),
    plazo_meses                integer,
    mensualidad                numeric(12, 2),
    tasa_anual                 numeric(6, 4),
    estimacion_toma_cuenta_id  bigint,
    prospecto_id               bigint,
    created_at                 timestamp(6) with time zone not null default now(),
    constraint fk_solicitud_estreno_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_solicitud_estreno_modelo foreign key (modelo_catalogo_id) references modelo_catalogo (id),
    constraint fk_solicitud_estreno_estimacion foreign key (estimacion_toma_cuenta_id)
        references estimacion_toma_cuenta (id),
    constraint fk_solicitud_estreno_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint ck_solicitud_estreno_tipo check (tipo in ('PRUEBA_MANEJO', 'COTIZACION')),
    constraint ck_solicitud_estreno_franja check (preferencia_franja is null or preferencia_franja in ('MANANA', 'TARDE'))
);

create index idx_solicitud_estreno_cliente on solicitud_estreno (cliente_id, created_at desc);

-- Los prospectos que nacen en la app quedan con origen APP en su historial.
alter table historial_etapa drop constraint ck_historial_etapa_origen;
alter table historial_etapa add constraint ck_historial_etapa_origen check (origen in ('CRM', 'ERP', 'APP'));

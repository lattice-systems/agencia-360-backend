-- Módulo carecarapp (APP-2.1 y APP-2.3): cuenta de la app de cada cliente,
-- sesiones (refresh tokens) y códigos de recuperación de contraseña.
--
-- El cliente entra con su correo (tabla cliente). La cuenta guarda la
-- contraseña solo como hash, si debe cambiarla en el primer ingreso, si está
-- activa y los intentos fallidos para bloquear el login 15 minutos tras 5.

create table cuenta_app (
    id                      bigint generated by default as identity primary key,
    cliente_id              bigint       not null,
    contrasena_hash         varchar(100) not null,
    debe_cambiar_contrasena boolean      not null,
    activa                  boolean      not null default true,
    intentos_fallidos       integer      not null default 0,
    bloqueada_hasta         timestamp(6) with time zone,
    created_at              timestamp(6) with time zone not null,
    updated_at              timestamp(6) with time zone not null,
    constraint fk_cuenta_app_cliente foreign key (cliente_id) references cliente (id),
    constraint uq_cuenta_app_cliente unique (cliente_id),
    constraint ck_cuenta_app_intentos check (intentos_fallidos >= 0)
);

-- Refresh tokens: solo se guarda el SHA-256 del token. Cada uno se usa una vez.
create table sesion_app (
    id          bigint generated by default as identity primary key,
    cuenta_id   bigint      not null,
    token_hash  varchar(64) not null,
    expira_en   timestamp(6) with time zone not null,
    revocada_en timestamp(6) with time zone,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint fk_sesion_app_cuenta foreign key (cuenta_id) references cuenta_app (id),
    constraint uq_sesion_app_token unique (token_hash)
);

create index idx_sesion_app_cuenta on sesion_app (cuenta_id);

-- Códigos de 6 dígitos que llegan por correo; se guardan como hash BCrypt.
create table codigo_recuperacion (
    id          bigint generated by default as identity primary key,
    cuenta_id   bigint       not null,
    codigo_hash varchar(100) not null,
    expira_en   timestamp(6) with time zone not null,
    usado_en    timestamp(6) with time zone,
    intentos    integer      not null default 0,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint fk_codigo_recuperacion_cuenta foreign key (cuenta_id) references cuenta_app (id),
    constraint ck_codigo_recuperacion_intentos check (intentos >= 0)
);

create index idx_codigo_recuperacion_cuenta on codigo_recuperacion (cuenta_id, created_at);

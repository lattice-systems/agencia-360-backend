-- Módulo ventascrm: reglas de etapas que definió el PO el 12 de octubre.
--
-- * Nueva etapa FINALIZADO: el vendedor la marca al entregar la unidad.
-- * Último cambio de etapa en el prospecto, para mostrarlo en la lista.
-- * Quién hizo cada cambio del historial.
-- * Solicitud de cierre: desde Pago en adelante, cerrar un prospecto requiere
--   que el Administrador del ERP apruebe la solicitud del vendedor.

alter table prospecto drop constraint ck_prospecto_etapa;
alter table prospecto add constraint ck_prospecto_etapa check (etapa in
    ('PRIMER_CONTACTO', 'VISITA', 'COTIZACION', 'PAGO', 'FACTURACION', 'ENTREGA', 'FINALIZADO', 'CERRADO'));

alter table historial_etapa drop constraint ck_historial_etapa_etapa;
alter table historial_etapa add constraint ck_historial_etapa_etapa check (etapa in
    ('PRIMER_CONTACTO', 'VISITA', 'COTIZACION', 'PAGO', 'FACTURACION', 'ENTREGA', 'FINALIZADO', 'CERRADO'));

-- Último cambio: los prospectos que ya existen toman la fecha de su último
-- movimiento del historial.
alter table prospecto add column etapa_actualizada_en timestamp(6) with time zone;
update prospecto p
   set etapa_actualizada_en = coalesce(
       (select max(h.fecha_hora) from historial_etapa h where h.prospecto_id = p.id),
       p.created_at);
alter table prospecto alter column etapa_actualizada_en set not null;

alter table prospecto add column cierre_pendiente boolean not null default false;

-- Quién hizo el cambio. Los movimientos anteriores quedan sin usuario.
alter table historial_etapa add column usuario_id bigint;
alter table historial_etapa add constraint fk_historial_etapa_usuario
    foreign key (usuario_id) references usuario (id);

create table solicitud_cierre (
    id              bigint generated by default as identity primary key,
    prospecto_id    bigint       not null,
    motivo          varchar(200) not null,
    solicitante_id  bigint       not null,
    estado          varchar(10)  not null,
    resuelta_por_id bigint,
    resuelta_en     timestamp(6) with time zone,
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null,
    constraint fk_solicitud_cierre_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint fk_solicitud_cierre_solicitante foreign key (solicitante_id) references usuario (id),
    constraint fk_solicitud_cierre_resuelta_por foreign key (resuelta_por_id) references usuario (id),
    constraint ck_solicitud_cierre_estado check (estado in ('PENDIENTE', 'APROBADA', 'RECHAZADA'))
);

-- El Administrador revisa las pendientes, de la más antigua a la más reciente.
create index idx_solicitud_cierre_estado on solicitud_cierre (estado, created_at);
-- Solo una solicitud pendiente por prospecto.
create unique index uq_solicitud_cierre_pendiente on solicitud_cierre (prospecto_id) where estado = 'PENDIENTE';

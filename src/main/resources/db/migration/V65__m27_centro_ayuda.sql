create table pregunta_frecuente (
    id          bigint generated by default as identity primary key,
    tema        varchar(80)   not null,
    pregunta    varchar(240)  not null,
    respuesta   varchar(4000) not null,
    orden       integer       not null default 0,
    activa      boolean       not null default true,
    created_at  timestamp(6) with time zone not null default now(),
    constraint ck_pregunta_frecuente_orden check (orden >= 0)
);
create index idx_pregunta_frecuente_activa on pregunta_frecuente (orden, id) where activa;

create table reporte_app (
    id             bigint generated by default as identity primary key,
    cuenta_app_id  bigint not null references cuenta_app (id),
    descripcion    varchar(2000) not null,
    version_app    varchar(40) not null,
    sistema        varchar(60) not null,
    dispositivo    varchar(120) not null,
    creado_en      timestamp(6) with time zone not null default now(),
    constraint ck_reporte_app_descripcion check (length(btrim(descripcion)) between 10 and 2000),
    constraint ck_reporte_app_version check (length(btrim(version_app)) > 0),
    constraint ck_reporte_app_sistema check (length(btrim(sistema)) > 0),
    constraint ck_reporte_app_dispositivo check (length(btrim(dispositivo)) > 0)
);
create index idx_reporte_app_cuenta_fecha on reporte_app (cuenta_app_id, creado_en desc);


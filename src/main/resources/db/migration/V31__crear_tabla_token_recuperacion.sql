create table token_recuperacion (
    id            bigint generated by default as identity primary key,
    cuenta_app_id bigint       not null,
    token_hash    varchar(64)  not null,
    codigo_hash   varchar(100) not null,
    expira        timestamp(6) with time zone not null,
    usado         boolean      not null default false,
    usado_en      timestamp(6) with time zone,
    intentos      integer      not null default 0,
    created_at    timestamp(6) with time zone not null,
    updated_at    timestamp(6) with time zone not null,
    constraint fk_token_recuperacion_cuenta foreign key (cuenta_app_id) references cuenta_app (id),
    constraint uq_token_recuperacion_token unique (token_hash),
    constraint ck_token_recuperacion_intentos check (intentos >= 0),
    constraint ck_token_recuperacion_usado check (usado = (usado_en is not null))
);

create index idx_token_recuperacion_cuenta on token_recuperacion (cuenta_app_id, created_at);

insert into token_recuperacion (cuenta_app_id, token_hash, codigo_hash, expira, usado, usado_en, intentos,
                                created_at, updated_at)
select cuenta_id,
       encode(sha256(convert_to(gen_random_uuid()::text || '-' || id::text, 'UTF8')), 'hex'),
       codigo_hash,
       expira_en,
       usado_en is not null,
       usado_en,
       intentos,
       created_at,
       updated_at
from codigo_recuperacion
order by id;

drop table codigo_recuperacion;

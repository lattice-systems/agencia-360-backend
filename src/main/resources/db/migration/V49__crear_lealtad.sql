-- Un canje guarda los puntos que costó por si después cambia la recompensa.
create table canje (
    id            bigint generated by default as identity primary key,
    cliente_id    bigint     not null,
    recompensa_id bigint     not null,
    codigo        varchar(8) not null,
    puntos        integer    not null,
    estado        varchar(8) not null,
    vence_en      timestamp(6) with time zone not null,
    usado_en      timestamp(6) with time zone,
    creado_en     timestamp(6) with time zone not null,
    constraint fk_canje_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_canje_recompensa foreign key (recompensa_id) references recompensa (id),
    constraint uq_canje_codigo unique (codigo),
    constraint ck_canje_estado check (estado in ('VIGENTE', 'USADO', 'VENCIDO')),
    constraint ck_canje_puntos check (puntos > 0),
    constraint ck_canje_usado check ((estado = 'USADO') = (usado_en is not null))
);

create index idx_canje_cliente on canje (cliente_id, creado_en desc, id desc);
create index idx_canje_vigente on canje (vence_en) where estado = 'VIGENTE';

-- Un amigo que el cliente refirió. Entra a ventascrm como prospecto por un
-- evento; prospecto_id se llena cuando ventascrm lo crea.
create table referido (
    id                bigint generated by default as identity primary key,
    cliente_id        bigint       not null,
    codigo            varchar(12)  not null,
    nombre            varchar(120) not null,
    telefono          varchar(10),
    correo            varchar(254),
    consentimiento_en timestamp(6) with time zone not null,
    prospecto_id      bigint,
    estado            varchar(15)  not null,
    recompensado_en   timestamp(6) with time zone,
    creado_en         timestamp(6) with time zone not null,
    constraint fk_referido_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_referido_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint uq_referido_prospecto unique (prospecto_id),
    constraint ck_referido_estado check (estado in ('REGISTRADO', 'EN_SEGUIMIENTO', 'COMPRO', 'DESCARTADO')),
    constraint ck_referido_contacto check (telefono is not null or correo is not null),
    constraint ck_referido_compro check ((estado = 'COMPRO') = (recompensado_en is not null))
);

create index idx_referido_cliente on referido (cliente_id, creado_en desc, id desc);
create index idx_referido_telefono on referido (telefono);
create index idx_referido_correo on referido (lower(correo));

-- Módulo ventascrm (CRM-1.0 y CRM-1.1): prospectos y su historial de etapas.
--
-- Etapas decididas por el PO el 9 de octubre: primer contacto, visita, cotización,
-- pago, facturación, entrega y cerrado (venta no concretada). Al cerrar se guarda
-- la última etapa alcanzada; el motivo de cierre llega con CRM-1.2.
--
-- La fecha y hora de registro es created_at (acordado con Ricardo el 12 de octubre).
-- vendedor_id solo se mapea como id en JPA para no cruzar módulos; la llave
-- foránea a usuario sí vive en la base.

create table prospecto (
    id            bigint generated by default as identity primary key,
    nombre        varchar(120) not null,
    telefono      varchar(20),
    correo        varchar(120),
    etapa         varchar(20)  not null,
    vendedor_id   bigint       not null,
    motivo_cierre varchar(200),
    ultima_etapa  varchar(20),
    created_at    timestamp(6) with time zone not null,
    updated_at    timestamp(6) with time zone not null,
    constraint fk_prospecto_vendedor foreign key (vendedor_id) references usuario (id),
    constraint ck_prospecto_contacto check (telefono is not null or correo is not null),
    constraint ck_prospecto_etapa check (etapa in
        ('PRIMER_CONTACTO', 'VISITA', 'COTIZACION', 'PAGO', 'FACTURACION', 'ENTREGA', 'CERRADO')),
    constraint ck_prospecto_ultima_etapa check (ultima_etapa in
        ('PRIMER_CONTACTO', 'VISITA', 'COTIZACION', 'PAGO', 'FACTURACION', 'ENTREGA'))
);

-- Listado por vendedor y etapa (CRM-1.1) y búsqueda de duplicados (CRM-1.0).
create index idx_prospecto_vendedor_etapa on prospecto (vendedor_id, etapa);
create index idx_prospecto_etapa on prospecto (etapa);
create index idx_prospecto_telefono on prospecto (telefono);
create index idx_prospecto_correo on prospecto (correo);

create table historial_etapa (
    id           bigint generated by default as identity primary key,
    prospecto_id bigint      not null,
    etapa        varchar(20) not null,
    origen       varchar(3)  not null,
    fecha_hora   timestamp(6) with time zone not null,
    constraint fk_historial_etapa_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint ck_historial_etapa_etapa check (etapa in
        ('PRIMER_CONTACTO', 'VISITA', 'COTIZACION', 'PAGO', 'FACTURACION', 'ENTREGA', 'CERRADO')),
    constraint ck_historial_etapa_origen check (origen in ('CRM', 'ERP'))
);

create index idx_historial_etapa_prospecto on historial_etapa (prospecto_id, fecha_hora);

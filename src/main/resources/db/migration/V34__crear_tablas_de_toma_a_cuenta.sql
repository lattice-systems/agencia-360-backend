-- V2-M03.04, V2-M03.06 y V2-M03.07 · Toma a cuenta.
--
-- parametro_toma_cuenta guarda lo que la agencia sabe de cada auto (valor de
-- referencia y factores de la fórmula). La fórmula vive en el backend
-- (CalculadoraTomaCuenta) y la app solo muestra el resultado. La migración no
-- trae filas: los valores reales los entrega el PO y, mientras no existan, la
-- app responde SIN_PARAMETROS_DE_VALUACION. Un parámetro que deja de usarse se
-- desactiva (activo = false), no se borra, porque las estimaciones lo citan.
--
-- estimacion_toma_cuenta es el historial del cliente. Guarda marca, modelo y
-- año aunque haya vehículo, y congela los supuestos, el modelo destino y su
-- precio, para que editar un vehículo o un parámetro no cambie lo que ya se
-- mostró. created_at es la fecha de la estimación.
create table parametro_toma_cuenta (
    id                 bigint generated by default as identity primary key,
    marca              varchar(40)    not null,
    modelo             varchar(80)    not null,
    anio               integer        not null,
    valor_base         numeric(12, 2) not null,
    depreciacion_anual numeric(5, 4)  not null,
    factor_km          numeric(5, 4)  not null,
    factor_estado      numeric(5, 4)  not null,
    activo             boolean        not null,
    created_at         timestamp(6) with time zone not null,
    updated_at         timestamp(6) with time zone not null,
    constraint ck_parametro_toma_cuenta_anio check (anio >= 1900),
    constraint ck_parametro_toma_cuenta_valor check (valor_base >= 0),
    constraint ck_parametro_toma_cuenta_depreciacion check (depreciacion_anual between 0 and 0.5),
    constraint ck_parametro_toma_cuenta_factor_km check (factor_km between 0 and 0.2),
    constraint ck_parametro_toma_cuenta_factor_estado check (factor_estado between 0 and 0.3)
);

create unique index uq_parametro_toma_cuenta on parametro_toma_cuenta (lower(marca), lower(modelo), anio);

create table estimacion_toma_cuenta (
    id                       bigint generated by default as identity primary key,
    cliente_id               bigint         not null,
    vehiculo_cliente_id      bigint,
    modelo_catalogo_id       bigint,
    marca                    varchar(40)    not null,
    modelo                   varchar(80)    not null,
    anio                     integer        not null,
    km                       integer        not null,
    estado                   varchar(10)    not null,
    minimo                   numeric(12, 2) not null,
    maximo                   numeric(12, 2) not null,
    parametro_toma_cuenta_id bigint         not null,
    supuestos                text           not null,
    modelo_destino           varchar(120),
    precio_destino           numeric(12, 2),
    created_at               timestamp(6) with time zone not null,
    updated_at               timestamp(6) with time zone not null,
    constraint fk_estimacion_toma_cuenta_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_estimacion_toma_cuenta_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint fk_estimacion_toma_cuenta_modelo foreign key (modelo_catalogo_id) references modelo_catalogo (id),
    constraint fk_estimacion_toma_cuenta_parametro foreign key (parametro_toma_cuenta_id) references parametro_toma_cuenta (id),
    constraint ck_estimacion_toma_cuenta_km check (km >= 0),
    constraint ck_estimacion_toma_cuenta_rango check (minimo <= maximo),
    constraint ck_estimacion_toma_cuenta_estado check (estado in ('EXCELENTE', 'BUENO', 'REGULAR', 'MALO'))
);

create index idx_estimacion_toma_cuenta_cliente on estimacion_toma_cuenta (cliente_id, created_at desc);

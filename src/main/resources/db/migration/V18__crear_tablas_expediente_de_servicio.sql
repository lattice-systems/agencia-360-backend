-- ERP-3.0 · Expediente del vehículo del cliente.
--
-- Servicio busca el vehículo por su VIN y ve arriba su número de serie, marca,
-- tipo, modelo y versión, y abajo los servicios que se le han hecho, por
-- fecha. Cada servicio es como el ticket de una tienda: renglones con su
-- concepto, cantidad y precio, y el total con el IVA incluido.
--
-- Los servicios son dinero: no se editan ni se borran.

-- La marca y la versión se copian de la unidad del inventario, como el VIN, el
-- tipo y el modelo. Los vehículos que ya existen quedan sin ellas.
alter table vehiculo_cliente add column marca varchar(40);
alter table vehiculo_cliente add column version varchar(80);

-- atendido_por es el usuario de Servicio que registró el servicio. Los montos
-- se guardan como se calcularon: el total es la suma de los renglones y ya
-- trae el IVA; de ahí se desglosan el subtotal y el IVA del 16 %.
create table servicio (
    id                  bigint generated by default as identity primary key,
    vehiculo_cliente_id bigint         not null,
    fecha               date           not null,
    kilometraje         integer        not null,
    atendido_por        bigint         not null,
    subtotal            numeric(12, 2) not null,
    iva                 numeric(12, 2) not null,
    total               numeric(12, 2) not null,
    created_at          timestamp(6) with time zone not null,
    updated_at          timestamp(6) with time zone not null,
    constraint fk_servicio_vehiculo_cliente foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint fk_servicio_atendido_por foreign key (atendido_por) references usuario (id),
    constraint ck_servicio_kilometraje check (kilometraje >= 0),
    constraint ck_servicio_montos check (subtotal >= 0 and iva >= 0 and total = subtotal + iva)
);

create index idx_servicio_vehiculo_cliente on servicio (vehiculo_cliente_id, fecha);

create table renglon_servicio (
    id              bigint generated by default as identity primary key,
    servicio_id     bigint         not null,
    tipo            varchar(15)    not null,
    concepto        varchar(200)   not null,
    cantidad        integer        not null,
    precio_unitario numeric(12, 2) not null,
    importe         numeric(12, 2) not null,
    constraint fk_renglon_servicio_servicio foreign key (servicio_id) references servicio (id),
    constraint ck_renglon_servicio_tipo check (tipo in ('MANO_DE_OBRA', 'REFACCION')),
    constraint ck_renglon_servicio_cantidad check (cantidad > 0),
    constraint ck_renglon_servicio_precio check (precio_unitario >= 0),
    constraint ck_renglon_servicio_importe check (importe = cantidad * precio_unitario)
);

create index idx_renglon_servicio_servicio on renglon_servicio (servicio_id);

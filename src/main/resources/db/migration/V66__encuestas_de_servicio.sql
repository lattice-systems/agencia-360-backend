create table encuesta_servicio (
    id bigint generated by default as identity primary key,
    orden_servicio_id bigint not null unique references orden_servicio(id),
    cliente_id bigint not null references cliente(id),
    asesor_id bigint references usuario(id),
    nps smallint check (nps between 0 and 10),
    tiempo smallint check (tiempo between 1 and 5),
    trato smallint check (trato between 1 and 5),
    limpieza smallint check (limpieza between 1 and 5),
    calificacion_asesor smallint check (calificacion_asesor between 1 and 5),
    comentario varchar(1000),
    pide_contacto boolean not null default false,
    respondida_en timestamp with time zone,
    pospuesta_hasta timestamp with time zone,
    check (not pide_contacto or (nps is not null and nps <= 6)),
    check (respondida_en is null or (
        nps is not null and tiempo is not null and trato is not null and limpieza is not null
        and calificacion_asesor is not null
    ))
);

create index idx_encuesta_servicio_periodo on encuesta_servicio(respondida_en, asesor_id)
    where respondida_en is not null;

create table tarea_contacto_encuesta (
    id bigint generated by default as identity primary key,
    encuesta_servicio_id bigint not null unique references encuesta_servicio(id),
    asesor_id bigint references usuario(id),
    creada_en timestamp with time zone not null default now(),
    cerrada_en timestamp with time zone,
    respuesta varchar(1000)
);

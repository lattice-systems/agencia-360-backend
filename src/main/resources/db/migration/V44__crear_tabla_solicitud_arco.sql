-- Solicitudes de derechos ARCO de la cuenta de la app (V2-M22.02): acceso,
-- rectificación, cancelación y oposición (LFPDPPP).
--
-- `archivo_url` guarda la ruta de la API desde la que se descarga la copia (el
-- nombre es el de la ficha); los bytes viven en `archivo_arco`, aparte: la
-- copia de los datos de una persona se entrega solo con su sesión, nunca por
-- las URL firmadas del módulo `archivos`. `resuelta_en` se llena también al
-- fallar, para saber cuándo terminó el intento.

create table solicitud_arco (
    id          bigint generated by default as identity primary key,
    cliente_id  bigint       not null,
    tipo        varchar(20)  not null,
    estado      varchar(20)  not null,
    archivo_url varchar(255),
    creada_en   timestamp(6) with time zone not null,
    resuelta_en timestamp(6) with time zone,
    constraint fk_solicitud_arco_cliente foreign key (cliente_id) references cliente (id),
    constraint ck_solicitud_arco_tipo check (tipo in ('ACCESO', 'RECTIFICACION', 'CANCELACION', 'OPOSICION')),
    constraint ck_solicitud_arco_estado check (estado in ('PENDIENTE', 'RESUELTA', 'FALLIDA'))
);

create index idx_solicitud_arco_cliente on solicitud_arco (cliente_id, creada_en desc);

-- Una sola solicitud pendiente por cuenta y tipo: dos toques seguidos, o dos
-- teléfonos, no abren dos archivos.
create unique index uq_solicitud_arco_pendiente on solicitud_arco (cliente_id, tipo) where estado = 'PENDIENTE';

-- La copia de los datos, uno por solicitud. Se borra al vencer o al pedir otra.
create table archivo_arco (
    solicitud_arco_id bigint       primary key,
    contenido         bytea        not null,
    tamano_bytes      bigint       not null,
    created_at        timestamp(6) with time zone not null default now(),
    constraint fk_archivo_arco_solicitud foreign key (solicitud_arco_id) references solicitud_arco (id),
    constraint ck_archivo_arco_tamano check (tamano_bytes > 0 and tamano_bytes = octet_length(contenido))
);

-- APP-3.3 · Citas de servicio que el cliente agenda desde la app CareCar.
--
-- Las franjas no viven en la base: salen del horario del taller configurado en
-- app.agenda.* (por omisión lunes a sábado de 9:00 a 17:00, franjas de una hora).
-- franja_id es el número de la franja dentro del día (1 = la primera). La hora
-- de inicio y de fin se copian al agendar para que la cita no cambie si el
-- horario se mueve después. Fechas y horas son hora local de la agencia.
--
-- El cupo de una franja es la capacidad configurada menos sus citas
-- CONFIRMADA. Un vehículo no puede tener dos citas confirmadas en la misma
-- franja del mismo día.
create table cita (
    id                  bigint generated by default as identity primary key,
    cliente_id          bigint      not null,
    vehiculo_cliente_id bigint      not null,
    fecha               date        not null,
    franja_id           bigint      not null,
    hora_inicio         time        not null,
    hora_fin            time        not null,
    estado              varchar(15) not null,
    cancelada_en        timestamp(6) with time zone,
    created_at          timestamp(6) with time zone not null,
    updated_at          timestamp(6) with time zone not null,
    constraint fk_cita_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_cita_vehiculo_cliente foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint ck_cita_estado check (estado in ('CONFIRMADA', 'ATENDIDA', 'NO_ASISTIO', 'CANCELADA')),
    constraint ck_cita_horas check (hora_fin > hora_inicio),
    constraint ck_cita_franja check (franja_id > 0)
);

create index idx_cita_cliente on cita (cliente_id, fecha, hora_inicio);
create index idx_cita_franja on cita (fecha, franja_id) where estado = 'CONFIRMADA';
create unique index uq_cita_vehiculo_franja on cita (vehiculo_cliente_id, fecha, franja_id) where estado = 'CONFIRMADA';

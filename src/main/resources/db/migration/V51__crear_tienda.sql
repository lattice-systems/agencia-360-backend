-- V2-M14 · Tienda de refacciones y accesorios (tablas de la ficha, sección 14).
--
-- refaccion y movimiento_inventario ya existían: solo ganan campos.
alter table refaccion add column publicada_en_app boolean not null default false;
alter table refaccion add column categoria_app varchar(12);
alter table refaccion add column descripcion_app varchar(1000);
alter table refaccion add column foto_url varchar(500);
alter table refaccion add column universal_app boolean not null default false;
alter table refaccion add constraint ck_refaccion_categoria_app check
    (categoria_app is null or categoria_app in ('ACCESORIO', 'REFACCION', 'CUIDADO'));
alter table refaccion add constraint ck_refaccion_publicada check
    (not publicada_en_app or categoria_app is not null);

create table compatibilidad_refaccion (
    id           bigint generated by default as identity primary key,
    refaccion_id bigint      not null,
    modelo       varchar(60) not null,
    anio_desde   integer     not null,
    anio_hasta   integer     not null,
    constraint fk_compatibilidad_refaccion foreign key (refaccion_id) references refaccion (id),
    constraint ck_compatibilidad_anios check (anio_desde <= anio_hasta)
);

create index ix_compatibilidad_refaccion on compatibilidad_refaccion (refaccion_id);

create table pedido_app (
    id                 bigint generated by default as identity primary key,
    cliente_id         bigint         not null,
    estado             varchar(10)    not null,
    entrega            varchar(10)    not null,
    cita_id            bigint,
    total              numeric(12, 2) not null,
    vence_en           timestamp(6) with time zone,
    llave_idempotencia varchar(64)    not null,
    listo_en           timestamp(6) with time zone,
    entregado_en       timestamp(6) with time zone,
    cancelado_en       timestamp(6) with time zone,
    motivo_cancelacion varchar(10),
    created_at         timestamp(6) with time zone not null,
    updated_at         timestamp(6) with time zone not null,
    constraint fk_pedido_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_pedido_cita foreign key (cita_id) references cita (id),
    constraint uq_pedido_llave unique (cliente_id, llave_idempotencia),
    constraint ck_pedido_estado check (estado in ('APARTADO', 'LISTO', 'ENTREGADO', 'CANCELADO')),
    constraint ck_pedido_entrega check (entrega in ('MOSTRADOR', 'CITA')),
    constraint ck_pedido_con_cita check ((entrega = 'CITA') = (cita_id is not null)),
    constraint ck_pedido_motivo check
        (motivo_cancelacion is null or motivo_cancelacion in ('CLIENTE', 'VENCIDO', 'AGENCIA')),
    constraint ck_pedido_cancelado check ((estado = 'CANCELADO') = (motivo_cancelacion is not null)),
    constraint ck_pedido_vigencia check ((estado in ('APARTADO', 'LISTO')) = (vence_en is not null)),
    constraint ck_pedido_total check (total >= 0)
);

create index ix_pedido_cliente on pedido_app (cliente_id, created_at desc);
create index ix_pedido_cita on pedido_app (cita_id);
create index ix_pedido_vigentes on pedido_app (vence_en) where estado in ('APARTADO', 'LISTO');

create table pedido_app_renglon (
    id            bigint generated by default as identity primary key,
    pedido_app_id bigint         not null,
    refaccion_id  bigint         not null,
    cantidad      integer        not null,
    precio        numeric(12, 2) not null,
    constraint fk_renglon_pedido foreign key (pedido_app_id) references pedido_app (id),
    constraint fk_renglon_refaccion foreign key (refaccion_id) references refaccion (id),
    constraint uq_renglon_pedido_refaccion unique (pedido_app_id, refaccion_id),
    constraint ck_renglon_pedido_cantidad check (cantidad > 0),
    constraint ck_renglon_pedido_precio check (precio > 0)
);

-- Cada apartado o liberación de un pedido es un movimiento. El cliente de la app
-- no es usuario del personal, así que esos movimientos no tienen responsable, y
-- la entrada que libera piezas no viene de un proveedor.
alter table movimiento_inventario add column pedido_app_id bigint;
alter table movimiento_inventario add constraint fk_movimiento_pedido
    foreign key (pedido_app_id) references pedido_app (id);
alter table movimiento_inventario add constraint ck_movimiento_pedido_refaccion check
    (pedido_app_id is null or refaccion_id is not null);
alter table movimiento_inventario alter column responsable_id drop not null;
alter table movimiento_inventario add constraint ck_movimiento_con_responsable check
    (responsable_id is not null or pedido_app_id is not null);
alter table movimiento_inventario drop constraint ck_movimiento_proveedor;
alter table movimiento_inventario add constraint ck_movimiento_proveedor check
    (refaccion_id is null or tipo <> 'ENTRADA' or proveedor is not null or pedido_app_id is not null);

create index ix_movimiento_pedido on movimiento_inventario (pedido_app_id);

-- Módulo inventario (ERP-2.0): vehículos, refacciones y sus movimientos.
--
-- Los vehículos se registran uno por uno (VIN único) y las refacciones por
-- existencia. El inventario se lleva por movimientos: cada entrada o salida queda
-- registrada con su fecha, cantidad y responsable, y no se borra.
--
-- Estatus del vehículo decididos por el PO el 9 de octubre: Disponible, Apartada,
-- Vendido, Entregado y No disponible.

create table vehiculo (
    id          bigint generated by default as identity primary key,
    vin         varchar(17)    not null,
    modelo      varchar(80)    not null,
    version     varchar(80)    not null,
    anio        integer        not null,
    color       varchar(40)    not null,
    precio      numeric(12, 2) not null,
    estatus     varchar(20)    not null,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint uq_vehiculo_vin unique (vin),
    constraint ck_vehiculo_precio check (precio > 0),
    constraint ck_vehiculo_estatus check (estatus in
        ('DISPONIBLE', 'APARTADA', 'VENDIDO', 'ENTREGADO', 'NO_DISPONIBLE'))
);

create index idx_vehiculo_estatus on vehiculo (estatus);

create table refaccion (
    id          bigint generated by default as identity primary key,
    codigo      varchar(40)    not null,
    descripcion varchar(200)   not null,
    costo       numeric(12, 2) not null,
    precio      numeric(12, 2) not null,
    existencia  integer        not null default 0,
    minimo      integer        not null,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint uq_refaccion_codigo unique (codigo),
    constraint ck_refaccion_costo check (costo >= 0),
    constraint ck_refaccion_precio check (precio > 0),
    -- ERP-2.1: la existencia nunca queda negativa.
    constraint ck_refaccion_existencia check (existencia >= 0),
    constraint ck_refaccion_minimo check (minimo >= 0)
);

-- responsable_id solo se mapea como id en JPA para no cruzar módulos; la llave
-- foránea a usuario sí vive en la base.
create table movimiento_inventario (
    id             bigint generated by default as identity primary key,
    tipo           varchar(7) not null,
    vehiculo_id    bigint,
    refaccion_id   bigint,
    cantidad       integer    not null,
    responsable_id bigint     not null,
    fecha          timestamp(6) with time zone not null,
    constraint fk_movimiento_vehiculo foreign key (vehiculo_id) references vehiculo (id),
    constraint fk_movimiento_refaccion foreign key (refaccion_id) references refaccion (id),
    constraint fk_movimiento_responsable foreign key (responsable_id) references usuario (id),
    constraint ck_movimiento_tipo check (tipo in ('ENTRADA', 'SALIDA')),
    constraint ck_movimiento_cantidad check (cantidad > 0),
    -- Cada movimiento es de un vehículo o de una refacción, nunca de los dos.
    constraint ck_movimiento_articulo check ((vehiculo_id is null) <> (refaccion_id is null)),
    -- Un vehículo es una sola unidad.
    constraint ck_movimiento_cantidad_vehiculo check (vehiculo_id is null or cantidad = 1)
);

create index idx_movimiento_vehiculo on movimiento_inventario (vehiculo_id, fecha);
create index idx_movimiento_refaccion on movimiento_inventario (refaccion_id, fecha);
create index idx_movimiento_responsable on movimiento_inventario (responsable_id);

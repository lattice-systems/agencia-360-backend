-- V2-M05 y V2-M18 · Plan de mantenimiento, lecturas de kilometraje y gastos.
--
-- Columnas de la ficha técnica v2.1. modelo es el Tipo (March) y el año del
-- vehículo debe caer entre anio_desde y anio_hasta. lectura_km guarda lo que el
-- cliente captura aparte del kilometraje oficial del taller, que no se
-- sobrescribe. gasto_vehiculo agrega descripcion (el tipo "otro" la exige) y
-- lectura_km_id (la lectura que creó una carga de gasolina).
create table plan_mantenimiento (
    id               bigint generated by default as identity primary key,
    modelo           varchar(80)    not null,
    anio_desde       integer        not null,
    anio_hasta       integer        not null,
    km               integer        not null,
    meses            integer        not null,
    nombre           varchar(100)   not null,
    precio_estimado  numeric(10, 2) not null,
    constraint ck_plan_mantenimiento_anios check (anio_desde >= 1900 and anio_hasta >= anio_desde),
    constraint ck_plan_mantenimiento_km check (km > 0),
    constraint ck_plan_mantenimiento_meses check (meses > 0),
    constraint ck_plan_mantenimiento_precio check (precio_estimado >= 0)
);

create index idx_plan_mantenimiento_modelo on plan_mantenimiento (lower(modelo), anio_desde, anio_hasta);

create table concepto_mantenimiento (
    id                     bigint generated by default as identity primary key,
    plan_mantenimiento_id  bigint       not null,
    concepto               varchar(120) not null,
    constraint fk_concepto_mantenimiento_plan foreign key (plan_mantenimiento_id) references plan_mantenimiento (id)
);

create index idx_concepto_mantenimiento_plan on concepto_mantenimiento (plan_mantenimiento_id);

create table lectura_km (
    id                  bigint generated by default as identity primary key,
    vehiculo_cliente_id bigint       not null,
    km                  integer      not null,
    fuente              varchar(10)  not null,
    foto_url            varchar(500),
    registrada_en       timestamp(6) with time zone not null,
    constraint fk_lectura_km_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint ck_lectura_km_km check (km > 0),
    constraint ck_lectura_km_fuente check (fuente in ('TALLER', 'CLIENTE'))
);

create index idx_lectura_km_vehiculo on lectura_km (vehiculo_cliente_id, registrada_en);

create table gasto_vehiculo (
    id                  bigint generated by default as identity primary key,
    vehiculo_cliente_id bigint         not null,
    tipo                varchar(15)    not null,
    monto               numeric(10, 2) not null,
    litros              numeric(8, 2),
    km                  integer,
    fecha               date           not null,
    ticket_url          varchar(500),
    descripcion         varchar(200),
    lectura_km_id       bigint,
    created_at          timestamp(6) with time zone not null,
    updated_at          timestamp(6) with time zone not null,
    constraint fk_gasto_vehiculo_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint fk_gasto_vehiculo_lectura foreign key (lectura_km_id) references lectura_km (id),
    constraint ck_gasto_vehiculo_tipo check (tipo in ('GASOLINA', 'ESTACIONAMIENTO', 'CASETAS', 'LAVADO', 'OTRO')),
    constraint ck_gasto_vehiculo_monto check (monto > 0),
    constraint ck_gasto_vehiculo_litros check (litros is null or litros > 0),
    constraint ck_gasto_vehiculo_km check (km is null or km > 0)
);

create index idx_gasto_vehiculo_vehiculo on gasto_vehiculo (vehiculo_cliente_id, fecha desc, id desc);

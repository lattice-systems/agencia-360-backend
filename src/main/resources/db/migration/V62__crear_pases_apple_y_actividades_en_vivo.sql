-- V2-M25.06 y V2-M25.05: lo que Apple obliga a recordar entre peticiones.
--
-- `registro_pase_apple`: cada dispositivo que guardó el pase de una cita en
-- Apple Wallet se registra en nuestro servicio web (webServiceURL) con su
-- push token. `serial` es el serialNumber del pase ("cita-<id>") y `cita_id`
-- el id numérico de la cita, para consultar sin interpretar texto. El estado
-- del pase (anulado o con fecha nueva) no se guarda: se arma al vuelo desde
-- la cita, y `cita.updated_at` es la marca de "última actualización".
--
-- `actividad_en_vivo`: cada Live Activity de la orden en la pantalla
-- bloqueada del cliente, con el push token que da ActivityKit. Una misma orden
-- puede tener varias (varios dispositivos); `activa` pasa a false al
-- entregarse la orden, al cerrar sesión o cuando Apple dice que el token murió.
create table registro_pase_apple (
    id           bigint generated by default as identity primary key,
    dispositivo  varchar(100) not null,
    push_token   varchar(200) not null,
    pass_type_id varchar(100) not null,
    serial       varchar(40)  not null,
    cita_id      bigint       not null,
    created_at   timestamp(6) with time zone not null default now(),
    updated_at   timestamp(6) with time zone not null default now(),
    constraint fk_registro_pase_apple_cita foreign key (cita_id) references cita (id),
    constraint uq_registro_pase_apple unique (dispositivo, pass_type_id, serial)
);

create index idx_registro_pase_apple_cita on registro_pase_apple (cita_id);
create index idx_registro_pase_apple_dispositivo on registro_pase_apple (dispositivo, pass_type_id);

create table actividad_en_vivo (
    id                bigint generated by default as identity primary key,
    cliente_id        bigint       not null,
    orden_servicio_id bigint       not null,
    push_token        varchar(300) not null,
    activa            boolean      not null default true,
    created_at        timestamp(6) with time zone not null default now(),
    updated_at        timestamp(6) with time zone not null default now(),
    constraint fk_actividad_en_vivo_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_actividad_en_vivo_orden foreign key (orden_servicio_id) references orden_servicio (id),
    constraint uq_actividad_en_vivo_token unique (orden_servicio_id, push_token)
);

create index idx_actividad_en_vivo_orden_activa on actividad_en_vivo (orden_servicio_id) where activa;
create index idx_actividad_en_vivo_cliente on actividad_en_vivo (cliente_id, orden_servicio_id);

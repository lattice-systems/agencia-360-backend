-- V2-M05.05 · Recordatorio del próximo servicio.
--
-- Una fila por (vehículo, servicio del plan) ya avisado: el job diario no
-- vuelve a avisar el mismo servicio. motivo es km o tiempo (lo que llegó
-- primero al umbral).
create table recordatorio_mantenimiento (
    id                    bigint generated by default as identity primary key,
    vehiculo_cliente_id   bigint       not null,
    plan_mantenimiento_id bigint       not null,
    motivo                varchar(10)  not null,
    enviado_en            timestamp(6) with time zone not null,
    constraint fk_recordatorio_mantenimiento_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint fk_recordatorio_mantenimiento_plan foreign key (plan_mantenimiento_id) references plan_mantenimiento (id),
    constraint ck_recordatorio_mantenimiento_motivo check (motivo in ('km', 'tiempo')),
    constraint uq_recordatorio_mantenimiento unique (vehiculo_cliente_id, plan_mantenimiento_id)
);

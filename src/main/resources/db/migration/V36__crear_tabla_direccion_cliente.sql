-- V2-M17.01 · Direcciones guardadas del cliente para pedir recolección.
--
-- Columnas de la ficha técnica v2.1 (cp es el código postal). El pin del mapa
-- (lat, lng) es obligatorio porque con él se valida la zona de cobertura.
create table direccion_cliente (
    id         bigint generated by default as identity primary key,
    cliente_id bigint        not null,
    alias      varchar(40)   not null,
    calle      varchar(120)  not null,
    colonia    varchar(80)   not null,
    cp         varchar(5)    not null,
    ciudad     varchar(80)   not null,
    lat        numeric(9, 6) not null,
    lng        numeric(9, 6) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint fk_direccion_cliente_cliente foreign key (cliente_id) references cliente (id),
    constraint ck_direccion_cliente_cp check (cp ~ '^[0-9]{5}$'),
    constraint ck_direccion_cliente_pin check (lat between -90 and 90 and lng between -180 and 180)
);

create index idx_direccion_cliente_cliente on direccion_cliente (cliente_id, id);

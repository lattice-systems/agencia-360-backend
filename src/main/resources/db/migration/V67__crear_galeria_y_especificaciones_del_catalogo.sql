-- V2-M03.02 · Detalle de un modelo del catálogo: galería de fotos y ficha resumida.
--
-- Son las tablas modelo_catalogo_imagen y modelo_catalogo_especificacion de la
-- ficha técnica. Cada fila es de una versión del catálogo (modelo_catalogo) y se
-- borra con ella; un modelo que deja de venderse se retira, no se borra.
create table modelo_catalogo_imagen (
    id                 bigint generated by default as identity primary key,
    modelo_catalogo_id bigint       not null references modelo_catalogo (id) on delete cascade,
    url                varchar(500) not null,
    color              varchar(40),
    descripcion        varchar(120),
    orden              integer      not null,
    created_at         timestamp(6) with time zone not null,
    updated_at         timestamp(6) with time zone not null,
    constraint ck_modelo_catalogo_imagen_orden check (orden >= 0),
    constraint ck_modelo_catalogo_imagen_url check (url like 'https://%')
);

create unique index uq_modelo_catalogo_imagen_orden on modelo_catalogo_imagen (modelo_catalogo_id, orden);

create table modelo_catalogo_especificacion (
    id                 bigint generated by default as identity primary key,
    modelo_catalogo_id bigint       not null references modelo_catalogo (id) on delete cascade,
    etiqueta           varchar(60)  not null,
    valor              varchar(120) not null,
    orden              integer      not null,
    created_at         timestamp(6) with time zone not null,
    updated_at         timestamp(6) with time zone not null,
    constraint ck_modelo_catalogo_especificacion_orden check (orden >= 0)
);

create unique index uq_modelo_catalogo_especificacion_orden
    on modelo_catalogo_especificacion (modelo_catalogo_id, orden);

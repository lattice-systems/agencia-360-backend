alter table orden_servicio rename constraint fk_servicio_vehiculo_cliente to fk_orden_servicio_vehiculo_cliente;
alter table orden_servicio rename constraint fk_servicio_atendido_por to fk_orden_servicio_atendido_por;
alter table orden_servicio rename constraint ck_servicio_kilometraje to ck_orden_servicio_kilometraje;
alter table orden_servicio rename constraint ck_servicio_montos to ck_orden_servicio_montos;
alter index idx_servicio_vehiculo_cliente rename to idx_orden_servicio_vehiculo_cliente;
alter sequence servicio_id_seq rename to orden_servicio_id_seq;

alter table orden_servicio add column mano_de_obra numeric(12, 2);
alter table orden_servicio add column refacciones numeric(12, 2);
alter table orden_servicio add column estatus varchar(15);
alter table orden_servicio add column fecha_cierre timestamp(6) with time zone;

create table orden_mano_de_obra (
    id                bigint generated by default as identity primary key,
    orden_servicio_id bigint         not null,
    concepto          varchar(200)   not null,
    cantidad          integer        not null,
    precio            numeric(12, 2) not null,
    importe           numeric(12, 2) not null,
    constraint fk_orden_mano_de_obra_orden foreign key (orden_servicio_id) references orden_servicio (id),
    constraint ck_orden_mano_de_obra_cantidad check (cantidad > 0),
    constraint ck_orden_mano_de_obra_precio check (precio >= 0),
    constraint ck_orden_mano_de_obra_importe check (importe = cantidad * precio)
);

create index idx_orden_mano_de_obra_orden on orden_mano_de_obra (orden_servicio_id);

create table orden_refaccion (
    id                bigint generated by default as identity primary key,
    orden_servicio_id bigint         not null,
    refaccion_id      bigint,
    concepto          varchar(200)   not null,
    cantidad          integer        not null,
    precio            numeric(12, 2) not null,
    importe           numeric(12, 2) not null,
    constraint fk_orden_refaccion_orden foreign key (orden_servicio_id) references orden_servicio (id),
    constraint fk_orden_refaccion_refaccion foreign key (refaccion_id) references refaccion (id),
    constraint ck_orden_refaccion_cantidad check (cantidad > 0),
    constraint ck_orden_refaccion_precio check (precio >= 0),
    constraint ck_orden_refaccion_importe check (importe = cantidad * precio)
);

create index idx_orden_refaccion_orden on orden_refaccion (orden_servicio_id);

insert into orden_mano_de_obra (orden_servicio_id, concepto, cantidad, precio, importe)
select servicio_id, concepto, cantidad, precio_unitario, importe
from renglon_servicio
where tipo = 'MANO_DE_OBRA'
order by id;

insert into orden_refaccion (orden_servicio_id, concepto, cantidad, precio, importe)
select servicio_id, concepto, cantidad, precio_unitario, importe
from renglon_servicio
where tipo = 'REFACCION'
order by id;

update orden_servicio o
set mano_de_obra = coalesce((select sum(m.importe) from orden_mano_de_obra m where m.orden_servicio_id = o.id), 0),
    refacciones  = coalesce((select sum(r.importe) from orden_refaccion r where r.orden_servicio_id = o.id), 0),
    estatus      = 'TERMINADO',
    fecha_cierre = o.created_at;

alter table orden_servicio alter column mano_de_obra set not null;
alter table orden_servicio alter column refacciones set not null;
alter table orden_servicio alter column estatus set not null;

alter table orden_servicio add constraint ck_orden_servicio_desglose
    check (mano_de_obra >= 0 and refacciones >= 0 and total = mano_de_obra + refacciones);
alter table orden_servicio add constraint ck_orden_servicio_estatus
    check (estatus in ('RECIBIDO', 'EN_PROCESO', 'TERMINADO', 'ENTREGADO'));
alter table orden_servicio add constraint ck_orden_servicio_cierre
    check ((estatus in ('TERMINADO', 'ENTREGADO')) = (fecha_cierre is not null));

drop table renglon_servicio;

-- ERP-1.3 · Emisión de factura (módulo facturacion).
--
-- Folio interno y PDF, sin timbrado (decisión 6 del modelo de datos). Ya no hay
-- elección previa de la unidad: al emitir la factura, en la misma transacción,
-- la unidad pasa de Disponible a Vendido y se registra la venta. Cuando el
-- vendedor finaliza el prospecto, la unidad sale del inventario y la venta
-- queda ENTREGADA.
--
-- La factura copia los datos del emisor, del receptor y de la unidad tal como
-- estaban al emitir, y guarda el PDF: no cambia aunque cambien después.

-- Ventas del Sprint 2: las que ya se finalizaron quedan entregadas; las que
-- solo tenían la unidad elegida, sin factura, se deshacen y la unidad regresa a
-- Disponible para que Facturación la elija al emitir.
alter table venta add column entregada_en timestamp(6) with time zone;
alter table venta drop constraint ck_venta_estatus;
alter table venta drop constraint ck_venta_unidad;

update venta set estatus = 'ENTREGADA', entregada_en = registrada_en where estatus = 'REGISTRADA';
update vehiculo set estatus = 'DISPONIBLE'
    where id in (select vehiculo_id from venta where estatus = 'POR_ENTREGAR') and estatus = 'VENDIDO';
delete from venta where estatus = 'POR_ENTREGAR';

alter table venta add constraint ck_venta_estatus check (estatus in ('REGISTRADA', 'ENTREGADA'));
-- Desde la factura toda venta tiene unidad; solo las entregadas del Sprint 2
-- pueden no tenerla.
alter table venta add constraint ck_venta_unidad check (estatus = 'ENTREGADA' or vehiculo_id is not null);

create sequence factura_folio_seq;

create table factura (
    id                        bigint generated by default as identity primary key,
    folio                     varchar(20)    not null,
    prospecto_id              bigint         not null,
    venta_id                  bigint         not null,
    vehiculo_id               bigint         not null,
    emisor_rfc                varchar(13)    not null,
    emisor_nombre             varchar(250)   not null,
    emisor_domicilio_fiscal   varchar(300)   not null,
    emisor_regimen_fiscal     varchar(150)   not null,
    receptor_rfc              varchar(13)    not null,
    receptor_nombre           varchar(250)   not null,
    receptor_domicilio_fiscal varchar(300)   not null,
    receptor_regimen_fiscal   varchar(150)   not null,
    unidad_vin                varchar(17)    not null,
    unidad_marca              varchar(40)    not null,
    unidad_modelo             varchar(80)    not null,
    unidad_version            varchar(80)    not null,
    unidad_anio               integer        not null,
    unidad_color              varchar(40)    not null,
    subtotal                  numeric(12, 2) not null,
    iva                       numeric(12, 2) not null,
    total                     numeric(12, 2) not null,
    pdf                       bytea          not null,
    emitida_por               bigint         not null,
    emitida_en                timestamp(6) with time zone not null,
    created_at                timestamp(6) with time zone not null,
    updated_at                timestamp(6) with time zone not null,
    constraint uq_factura_folio unique (folio),
    constraint uq_factura_prospecto unique (prospecto_id),
    constraint uq_factura_venta unique (venta_id),
    constraint uq_factura_vehiculo unique (vehiculo_id),
    constraint fk_factura_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint fk_factura_venta foreign key (venta_id) references venta (id),
    constraint fk_factura_vehiculo foreign key (vehiculo_id) references vehiculo (id),
    constraint fk_factura_emitida_por foreign key (emitida_por) references usuario (id),
    constraint ck_factura_total check (total > 0 and subtotal + iva = total)
);

create index idx_factura_emitida_en on factura (emitida_en);

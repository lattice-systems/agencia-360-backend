-- APP-6 · Notificaciones push de la app CareCar.
--
-- Cada teléfono donde el cliente inició sesión registra su token de Firebase
-- Cloud Messaging. Un token es de un solo teléfono: si otro cliente entra en
-- ese teléfono, el token pasa a él. Al cerrar sesión la app lo borra.
create table dispositivo_app (
    id          bigint generated by default as identity primary key,
    cliente_id  bigint        not null,
    token       varchar(4096) not null,
    plataforma  varchar(10)   not null,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint fk_dispositivo_app_cliente foreign key (cliente_id) references cliente (id),
    constraint uq_dispositivo_app_token unique (token),
    constraint ck_dispositivo_app_plataforma check (plataforma in ('ANDROID', 'IOS'))
);

create index idx_dispositivo_app_cliente on dispositivo_app (cliente_id);


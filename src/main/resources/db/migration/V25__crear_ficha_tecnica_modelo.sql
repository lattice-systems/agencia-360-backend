-- V2-M02.04 · Ficha técnica de los vehículos para la app CareCar.
--
-- Una fila por especificación de un modelo y año, agrupada en secciones
-- (Motor, Dimensiones, Seguridad…). Como en el inventario, modelo es el Tipo
-- (Sentra) y anio el Modelo (2026). La versión no cambia la ficha. Tabla
-- nueva de la app: no renombra ni toca ninguna tabla de la ficha técnica del
-- equipo.
create table ficha_tecnica_modelo (
    id         bigint generated by default as identity primary key,
    marca      varchar(40)  not null,
    modelo     varchar(80)  not null,
    anio       integer      not null,
    seccion    varchar(60)  not null,
    nombre     varchar(80)  not null,
    valor      varchar(200) not null,
    orden      integer      not null default 0,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint ck_ficha_tecnica_modelo_anio check (anio >= 1900)
);

create index idx_ficha_tecnica_modelo on ficha_tecnica_modelo (lower(marca), lower(modelo), anio, orden);

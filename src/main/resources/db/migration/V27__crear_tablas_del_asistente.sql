-- V2-M24.02 y V2-M24.03 · Asistente CareCar (ficha, sección 21; ADR 0007).
--
-- fragmento_manual guarda el texto de cada página de un manual y su vector para
-- buscar por parecido (pgvector, que Neon trae). El vector se calcula después,
-- despacio, por la cuota gratis del proveedor de IA: mientras tanto se busca por
-- texto completo en español.
--
-- consulta_asistente guarda cada pregunta y su respuesta con las páginas citadas
-- (fuentes) para medir la calidad (util) y aplicar el límite diario por cliente.

create extension if not exists vector;

create table fragmento_manual (
    id         bigint generated by default as identity primary key,
    manual_id  bigint       not null,
    pagina     integer      not null,
    texto      text         not null,
    embedding  vector(768),
    created_at timestamp(6) with time zone not null default now(),
    constraint fk_fragmento_manual_manual foreign key (manual_id) references manual (id) on delete cascade,
    constraint uq_fragmento_manual_pagina unique (manual_id, pagina),
    constraint ck_fragmento_manual_pagina check (pagina >= 1)
);

create index ix_fragmento_manual_texto on fragmento_manual using gin (to_tsvector('spanish', texto));
create index ix_fragmento_manual_embedding on fragmento_manual using hnsw (embedding vector_cosine_ops);

create table consulta_asistente (
    id                  bigint generated by default as identity primary key,
    cliente_id          bigint        not null,
    vehiculo_cliente_id bigint        not null,
    pregunta            varchar(500)  not null,
    respuesta           text          not null,
    fuentes             jsonb         not null default '[]'::jsonb,
    util                boolean,
    encontrado          boolean       not null,
    proveedor           varchar(40)   not null,
    created_at          timestamp(6) with time zone not null default now(),
    constraint fk_consulta_asistente_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_consulta_asistente_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id)
);

create index ix_consulta_asistente_cliente_fecha on consulta_asistente (cliente_id, created_at);
create index ix_consulta_asistente_fecha on consulta_asistente (created_at);

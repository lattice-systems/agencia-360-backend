-- V2-M11.04, V2-M17.03 y V2-M17.04 · Estado de la asistencia, seguimiento del
-- chofer y checklist del traslado.
--
-- solicitud_asistencia.cerrada_en marca cuándo se atendió o canceló; al cerrarse
-- también se borran lat y lng (privacidad). traslado guarda la última ubicación
-- del chofer, que solo existe mientras va en camino o de regreso.
-- checklist_traslado usa los nombres de la ficha técnica v2.1 (fotos es un
-- arreglo json de claves de archivos) y agrega notas y las marcas de tiempo.
alter table solicitud_asistencia
    add column cerrada_en timestamp(6) with time zone;

alter table traslado
    add column chofer_lat   numeric(9, 6),
    add column chofer_lng   numeric(9, 6),
    add column ubicacion_en timestamp(6) with time zone,
    add constraint ck_traslado_ubicacion_chofer
        check ((chofer_lat is null) = (chofer_lng is null) and (chofer_lat is null) = (ubicacion_en is null));

create table checklist_traslado (
    id          bigint generated by default as identity primary key,
    traslado_id bigint       not null,
    km          integer      not null,
    gasolina    varchar(15)  not null,
    notas       varchar(500),
    fotos       jsonb        not null default '[]'::jsonb,
    firma_url   varchar(500),
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint fk_checklist_traslado_traslado foreign key (traslado_id) references traslado (id),
    constraint uq_checklist_traslado_traslado unique (traslado_id),
    constraint ck_checklist_traslado_km check (km > 0),
    constraint ck_checklist_traslado_gasolina check (gasolina in ('VACIO', 'UN_CUARTO', 'MEDIO', 'TRES_CUARTOS', 'LLENO'))
);

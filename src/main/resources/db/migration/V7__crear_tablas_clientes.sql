-- Módulo clientes (CRM-1.5): los clientes de la agencia, separados de los
-- usuarios internos (tabla usuario).
--
-- Un cliente se crea cuando su prospecto llega a Finalizado (CRM-1.3) o lo da de
-- alta a mano el Gerente de marketing. Entra a la app con su correo, que no se
-- repite; si rechazó la app puede no tener correo. Puede tener varios vehículos.

create table cliente (
    id           bigint generated by default as identity primary key,
    nombre       varchar(120) not null,
    correo       varchar(120),
    telefono     varchar(20),
    prospecto_id bigint,
    created_at   timestamp(6) with time zone not null,
    updated_at   timestamp(6) with time zone not null,
    constraint fk_cliente_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint uq_cliente_prospecto unique (prospecto_id)
);

-- El correo se guarda en minúsculas; solo se exige único cuando existe.
create unique index uq_cliente_correo on cliente (correo) where correo is not null;

-- Vehículos del cliente. vehiculo_id liga la unidad del inventario cuando la
-- vendió la agencia; los datos se copian porque el expediente del cliente no
-- depende del inventario.
create table vehiculo_cliente (
    id          bigint generated by default as identity primary key,
    cliente_id  bigint      not null,
    vehiculo_id bigint,
    vin         varchar(17) not null,
    modelo      varchar(80) not null,
    anio        integer     not null,
    placas      varchar(15),
    kilometraje integer,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint fk_vehiculo_cliente_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_vehiculo_cliente_vehiculo foreign key (vehiculo_id) references vehiculo (id),
    constraint uq_vehiculo_cliente_vin unique (vin),
    constraint uq_vehiculo_cliente_vehiculo unique (vehiculo_id),
    constraint ck_vehiculo_cliente_kilometraje check (kilometraje is null or kilometraje >= 0)
);

create index idx_vehiculo_cliente_cliente on vehiculo_cliente (cliente_id);

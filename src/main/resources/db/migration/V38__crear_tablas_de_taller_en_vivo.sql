alter table orden_servicio add column cita_id bigint;
alter table orden_servicio add column asesor_id bigint;
alter table orden_servicio add column entrega_estimada timestamp(6) with time zone;
alter table orden_servicio add constraint fk_orden_servicio_cita foreign key (cita_id) references cita (id);
alter table orden_servicio add constraint fk_orden_servicio_asesor foreign key (asesor_id) references usuario (id);

create table etapa_orden (
    id                bigint generated by default as identity primary key,
    orden_servicio_id bigint       not null,
    etapa             varchar(25)  not null,
    inicio            timestamp(6) with time zone not null,
    fin               timestamp(6) with time zone,
    nota              varchar(300),
    created_at        timestamp(6) with time zone not null,
    updated_at        timestamp(6) with time zone not null,
    constraint fk_etapa_orden_orden foreign key (orden_servicio_id) references orden_servicio (id),
    constraint uq_etapa_orden_etapa unique (orden_servicio_id, etapa),
    constraint ck_etapa_orden_etapa check (etapa in ('RECIBIDO', 'DIAGNOSTICO', 'ESPERANDO_APROBACION',
        'EN_REPARACION', 'CONTROL_DE_CALIDAD', 'LAVADO', 'LISTO_PARA_ENTREGA', 'ENTREGADO')),
    constraint ck_etapa_orden_fin check (fin is null or fin >= inicio)
);

create index idx_etapa_orden_orden on etapa_orden (orden_servicio_id, inicio);

create table punto_inspeccion (
    id                bigint generated by default as identity primary key,
    orden_servicio_id bigint       not null,
    punto             varchar(120) not null,
    resultado         varchar(10)  not null,
    comentario        varchar(500),
    created_at        timestamp(6) with time zone not null,
    updated_at        timestamp(6) with time zone not null,
    constraint fk_punto_inspeccion_orden foreign key (orden_servicio_id) references orden_servicio (id),
    constraint ck_punto_inspeccion_resultado check (resultado in ('VERDE', 'AMARILLO', 'ROJO'))
);

create index idx_punto_inspeccion_orden on punto_inspeccion (orden_servicio_id);

create table evidencia_orden (
    id                  bigint generated by default as identity primary key,
    orden_servicio_id   bigint       not null,
    punto_inspeccion_id bigint,
    tipo                varchar(10)  not null,
    url                 varchar(300) not null,
    created_at          timestamp(6) with time zone not null,
    updated_at          timestamp(6) with time zone not null,
    constraint fk_evidencia_orden_orden foreign key (orden_servicio_id) references orden_servicio (id),
    constraint fk_evidencia_orden_punto foreign key (punto_inspeccion_id) references punto_inspeccion (id),
    constraint ck_evidencia_orden_tipo check (tipo in ('FOTO', 'VIDEO'))
);

create index idx_evidencia_orden_orden on evidencia_orden (orden_servicio_id);

create table trabajo_adicional (
    id                bigint generated by default as identity primary key,
    orden_servicio_id bigint         not null,
    concepto          varchar(200)   not null,
    mano_de_obra      numeric(12, 2) not null,
    refacciones       numeric(12, 2) not null,
    total             numeric(12, 2) not null,
    estado            varchar(10)    not null,
    respondido_en     timestamp(6) with time zone,
    respondido_por    bigint,
    firma_url         varchar(300),
    created_at        timestamp(6) with time zone not null,
    updated_at        timestamp(6) with time zone not null,
    constraint fk_trabajo_adicional_orden foreign key (orden_servicio_id) references orden_servicio (id),
    constraint fk_trabajo_adicional_cliente foreign key (respondido_por) references cliente (id),
    constraint ck_trabajo_adicional_montos
        check (mano_de_obra >= 0 and refacciones >= 0 and total = mano_de_obra + refacciones and total > 0),
    constraint ck_trabajo_adicional_estado check (estado in ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
    constraint ck_trabajo_adicional_respuesta check ((estado = 'PENDIENTE') =
        (respondido_en is null and respondido_por is null and firma_url is null)),
    constraint ck_trabajo_adicional_firma check (estado = 'PENDIENTE'
        or (respondido_en is not null and respondido_por is not null and firma_url is not null))
);

create index idx_trabajo_adicional_orden on trabajo_adicional (orden_servicio_id);

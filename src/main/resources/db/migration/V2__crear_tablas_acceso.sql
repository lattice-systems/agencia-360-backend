-- Módulo acceso (ERP-0.1 y CRM-0.1): roles y usuarios del personal de la agencia.
-- Los clientes de la app CareCar NO son usuarios de esta tabla: tendrán su propia
-- cuenta (cuenta_app) en el módulo de la app.
--
-- Cada usuario tiene un solo rol, y el rol define a qué aplicación entra (ERP, CRM
-- o ambas).

create table rol (
    id          bigint generated by default as identity primary key,
    nombre      varchar(50)  not null,
    descripcion varchar(150) not null,
    acceso_erp  boolean      not null,
    acceso_crm  boolean      not null,
    constraint uq_rol_nombre unique (nombre)
);

-- "nombre" debe coincidir con el enum shared.security.Role, porque es el valor que
-- viaja en el JWT y el que usa @PreAuthorize.
insert into rol (nombre, descripcion, acceso_erp, acceso_crm) values
    ('ADMINISTRADOR',     'Administrador del ERP: da de alta usuarios del ERP y tiene el dashboard general', true,  false),
    ('GERENTE_MARKETING', 'Administrador del CRM: da de alta usuarios del CRM y ve todos los prospectos',   false, true),
    ('VENTAS',            'Vendedor: registra prospectos y les da seguimiento en el CRM',                   false, true),
    ('FACTURACION',       'Verifica la liquidación de ventas y emite facturas',                               true,  false),
    ('INVENTARIO',        'Registra las unidades una por una y las refacciones por stock',                    true,  false),
    ('SERVICIO',          'Vehículos de clientes de otras agencias, órdenes de servicio y agenda del taller', true,  false),
    ('REFACCIONES',       'Ventas directas de refacciones',                                                   true,  false),
    ('CAJA',              'Registro de cobros',                                                               true,  false),
    ('CONTABILIDAD',      'Autoriza o rechaza pagos, da seguimiento a pagos y consulta el balance',           true,  true);

create table usuario (
    id              bigint generated by default as identity primary key,
    usuario         varchar(50)  not null,
    contrasena_hash varchar(100) not null,
    nombre          varchar(120) not null,
    activo          boolean      not null default true,
    rol_id          bigint       not null,
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null,
    constraint uq_usuario_usuario unique (usuario),
    constraint fk_usuario_rol foreign key (rol_id) references rol (id)
);

create index idx_usuario_rol_id on usuario (rol_id);

-- V2-M17.02 · Traslados de recolección y entrega ligados a una cita.
--
-- Columnas de la ficha técnica v2.1 más la fecha y la ventana de horas del
-- traslado. chofer_id queda nulo hasta que se asigne y sin llave foránea
-- mientras el ERP siga congelado. Cada cita tiene a lo más un traslado de cada
-- tipo. El estado lo amplía V2-M17.03; nace PROGRAMADO.
create table traslado (
    id                   bigint generated by default as identity primary key,
    cita_id              bigint        not null,
    direccion_cliente_id bigint        not null,
    tipo                 varchar(10)   not null,
    chofer_id            bigint,
    estado               varchar(15)   not null,
    costo                numeric(10, 2) not null,
    fecha                date          not null,
    ventana_inicio       time          not null,
    ventana_fin          time          not null,
    created_at           timestamp(6) with time zone not null,
    updated_at           timestamp(6) with time zone not null,
    constraint fk_traslado_cita foreign key (cita_id) references cita (id),
    constraint fk_traslado_direccion foreign key (direccion_cliente_id) references direccion_cliente (id),
    constraint ck_traslado_tipo check (tipo in ('RECOGER', 'ENTREGAR')),
    constraint ck_traslado_estado check (estado in ('PROGRAMADO', 'EN_CAMINO', 'RECOGIDO', 'EN_TALLER', 'DE_REGRESO', 'ENTREGADO', 'CANCELADO')),
    constraint ck_traslado_costo check (costo >= 0),
    constraint ck_traslado_ventana check (ventana_fin > ventana_inicio),
    constraint uq_traslado_cita_tipo unique (cita_id, tipo)
);

create index idx_traslado_direccion on traslado (direccion_cliente_id);

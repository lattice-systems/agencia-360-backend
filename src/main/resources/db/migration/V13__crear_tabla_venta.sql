-- ERP-1.0 · Venta de la unidad.
--
-- El PO quitó el apartado (19 de octubre): Facturación elige la unidad de un
-- prospecto que llegó a Facturación y la unidad pasa de Disponible a Vendido.
-- Es venta cuando el vendedor lleva el prospecto hasta Finalizado; entonces se
-- registra (registrada_en). Un prospecto tiene a lo más una venta y una unidad
-- se vende una sola vez. Si Facturación se equivoca, cambia la unidad mientras
-- la venta no esté registrada, y la anterior regresa a Disponible.
--
-- precio guarda el precio de la unidad al elegirla. El precio acordado con el
-- cliente lo captura el vendedor y lo valida Contabilidad en los pagos (ERP-1.1).

create table venta (
    id            bigint generated by default as identity primary key,
    prospecto_id  bigint         not null,
    vehiculo_id   bigint,
    precio        numeric(12, 2),
    estatus       varchar(20)    not null,
    asignada_por  bigint,
    asignada_en   timestamp(6) with time zone,
    registrada_en timestamp(6) with time zone,
    created_at    timestamp(6) with time zone not null,
    updated_at    timestamp(6) with time zone not null,
    constraint fk_venta_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint fk_venta_vehiculo foreign key (vehiculo_id) references vehiculo (id),
    constraint fk_venta_asignada_por foreign key (asignada_por) references usuario (id),
    constraint uq_venta_prospecto unique (prospecto_id),
    constraint uq_venta_vehiculo unique (vehiculo_id),
    constraint ck_venta_estatus check (estatus in ('POR_ENTREGAR', 'REGISTRADA')),
    -- Mientras no se registra, la venta siempre tiene su unidad.
    constraint ck_venta_unidad check (estatus = 'REGISTRADA' or vehiculo_id is not null)
);

-- Sin apartado, una unidad ya no puede quedar Apartada.
alter table vehiculo drop constraint ck_vehiculo_estatus;
alter table vehiculo add constraint ck_vehiculo_estatus check (estatus in
    ('DISPONIBLE', 'VENDIDO', 'ENTREGADO', 'NO_DISPONIBLE'));

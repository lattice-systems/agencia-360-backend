create table franja_horario (
    id          bigint generated by default as identity primary key,
    dia_semana  integer     not null,
    hora_inicio time        not null,
    hora_fin    time        not null,
    capacidad   integer     not null,
    activa      boolean     not null default true,
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint ck_franja_horario_dia check (dia_semana between 1 and 7),
    constraint ck_franja_horario_horas check (hora_fin > hora_inicio),
    constraint ck_franja_horario_capacidad check (capacidad > 0),
    constraint uq_franja_horario_inicio unique (dia_semana, hora_inicio)
);

insert into franja_horario (dia_semana, hora_inicio, hora_fin, capacidad, activa, created_at, updated_at)
select dia, time '09:00' + make_interval(hours => hora), time '10:00' + make_interval(hours => hora), 3, true, now(), now()
from generate_series(1, 6) as dia, generate_series(0, 7) as hora
order by dia, hora;

insert into franja_horario (dia_semana, hora_inicio, hora_fin, capacidad, activa, created_at, updated_at)
select distinct on (extract(isodow from c.fecha)::integer, c.hora_inicio)
       extract(isodow from c.fecha)::integer, c.hora_inicio, c.hora_fin, 1, false, now(), now()
from cita c
where not exists (select 1
                  from franja_horario f
                  where f.dia_semana = extract(isodow from c.fecha)::integer
                    and f.hora_inicio = c.hora_inicio)
order by extract(isodow from c.fecha)::integer, c.hora_inicio, c.hora_fin;

update cita c
set franja_id = f.id
from franja_horario f
where f.dia_semana = extract(isodow from c.fecha)::integer
  and f.hora_inicio = c.hora_inicio;

alter table cita drop constraint ck_cita_franja;

alter table cita add constraint fk_cita_franja_horario foreign key (franja_id) references franja_horario (id);

-- Módulo ventascrm (ERP-1.1): verificación de los pagos de la venta.
--
-- Decisión del PO del Sprint 2: Caja solo registra y envía los pagos;
-- Contabilidad valida que correspondan y cubran la venta, y con eso el
-- prospecto pasa de Pago a Facturación. Como ya no existe el apartado y la
-- venta se registra hasta Finalizado, los pagos se ligan al prospecto.

create table liquidacion (
    id              bigint generated by default as identity primary key,
    prospecto_id    bigint      not null,
    estado          varchar(10) not null,
    enviada_por_id  bigint,
    enviada_en      timestamp(6) with time zone,
    resuelta_por_id bigint,
    resuelta_en     timestamp(6) with time zone,
    motivo_rechazo  varchar(200),
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null,
    constraint uq_liquidacion_prospecto unique (prospecto_id),
    constraint fk_liquidacion_prospecto foreign key (prospecto_id) references prospecto (id),
    constraint fk_liquidacion_enviada_por foreign key (enviada_por_id) references usuario (id),
    constraint fk_liquidacion_resuelta_por foreign key (resuelta_por_id) references usuario (id),
    constraint ck_liquidacion_estado check (estado in ('ABIERTA', 'ENVIADA', 'VALIDADA', 'RECHAZADA'))
);

create table pago (
    id                bigint generated by default as identity primary key,
    liquidacion_id    bigint         not null,
    monto             numeric(12, 2) not null,
    fecha_pago        date           not null,
    referencia        varchar(60),
    registrado_por_id bigint         not null,
    -- El dinero no se borra: un pago mal capturado se anula y se queda aquí.
    anulado           boolean        not null default false,
    anulado_por_id    bigint,
    anulado_en        timestamp(6) with time zone,
    created_at        timestamp(6) with time zone not null,
    updated_at        timestamp(6) with time zone not null,
    constraint fk_pago_liquidacion foreign key (liquidacion_id) references liquidacion (id),
    constraint fk_pago_registrado_por foreign key (registrado_por_id) references usuario (id),
    constraint fk_pago_anulado_por foreign key (anulado_por_id) references usuario (id),
    constraint ck_pago_monto check (monto > 0)
);

create index idx_pago_liquidacion on pago (liquidacion_id);

-- V2-M12 · Lealtad y recompensas (ficha técnica, sección 12): puntos,
-- recompensas, canjes y referidos.
--
-- El saldo de un cliente es la suma de sus movimientos; un movimiento nunca se
-- borra ni se edita (un canje vencido regresa sus puntos con otro movimiento).
-- Un mismo motivo con la misma referencia solo puede sumar una vez, para que un
-- evento repetido no regale puntos.

create table movimiento_puntos (
    id              bigint generated by default as identity primary key,
    cliente_id      bigint      not null,
    puntos          integer     not null,
    motivo          varchar(20) not null,
    referencia_tipo varchar(20),
    referencia_id   bigint,
    creado_en       timestamp(6) with time zone not null,
    constraint fk_movimiento_puntos_cliente foreign key (cliente_id) references cliente (id),
    constraint ck_movimiento_puntos_motivo
        check (motivo in ('SERVICIO', 'CANJE', 'DEVOLUCION_CANJE', 'REFERIDO', 'AJUSTE')),
    constraint ck_movimiento_puntos_no_cero check (puntos <> 0),
    constraint ck_movimiento_puntos_referencia
        check ((referencia_tipo is null) = (referencia_id is null)),
    constraint uq_movimiento_puntos_referencia unique (motivo, referencia_tipo, referencia_id)
);

create index idx_movimiento_puntos_cliente on movimiento_puntos (cliente_id, creado_en desc, id desc);

-- Catálogo de recompensas. Sin existencia es ilimitada.
create table recompensa (
    id          bigint generated by default as identity primary key,
    nombre      varchar(80)  not null,
    descripcion varchar(300),
    puntos      integer      not null,
    activa      boolean      not null default true,
    existencia  integer,
    creado_en   timestamp(6) with time zone not null default now(),
    constraint ck_recompensa_puntos check (puntos > 0),
    constraint ck_recompensa_existencia check (existencia is null or existencia >= 0)
);


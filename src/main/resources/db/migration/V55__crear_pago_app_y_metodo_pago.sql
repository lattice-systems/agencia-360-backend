-- V2-M08.02, V2-M08.04 y V2-M08.07: pagos de órdenes de servicio desde la app
-- y tarjetas guardadas (tablas pago_app y metodo_pago de la ficha, sección 8).
-- El procesador es simulado y propio (ADR 0009 de carecar-mobile): no se mueve
-- dinero y nunca se recibe ni se guarda el número de una tarjeta, solo un token
-- de prueba, la marca, los últimos 4 y el vencimiento. El dinero no se borra:
-- un pago fallido o reembolsado se queda con su estado. Una orden se paga una
-- sola vez y no tiene dos intentos abiertos a la vez.

create table metodo_pago (
    id                    bigint generated by default as identity primary key,
    cliente_id            bigint      not null references cliente (id),
    procesador            varchar(20) not null,
    cliente_procesador_id varchar(64) not null,
    token_procesador      varchar(64) not null,
    marca                 varchar(20) not null,
    ultimos4              varchar(4)  not null,
    mes_vence             smallint    not null,
    anio_vence            smallint    not null,
    tipo                  varchar(10) not null,
    predeterminado        boolean     not null default false,
    creado_en             timestamp(6) with time zone not null default now(),
    constraint ck_metodo_pago_ultimos4 check (ultimos4 ~ '^[0-9]{4}$'),
    constraint ck_metodo_pago_mes check (mes_vence between 1 and 12),
    constraint ck_metodo_pago_anio check (anio_vence between 2000 and 2100),
    constraint ck_metodo_pago_tipo check (tipo in ('CREDITO', 'DEBITO')),
    constraint uq_metodo_pago_token unique (cliente_id, token_procesador)
);

create index ix_metodo_pago_cliente on metodo_pago (cliente_id, id);

create unique index uq_metodo_pago_predeterminado on metodo_pago (cliente_id) where predeterminado;

create table pago_app (
    id                  bigint generated by default as identity primary key,
    orden_servicio_id   bigint        not null references orden_servicio (id),
    vehiculo_cliente_id bigint        not null references vehiculo_cliente (id),
    cliente_id          bigint        not null references cliente (id),
    monto               numeric(12,2) not null,
    moneda              varchar(3)    not null default 'MXN',
    procesador          varchar(20)   not null,
    intencion_id        varchar(64)   not null,
    llave_idempotencia  varchar(64),
    metodo              varchar(15)   not null,
    marca               varchar(20),
    ultimos4            varchar(4),
    tipo_tarjeta        varchar(10),
    token_procesador    varchar(64),
    mes_vence           smallint,
    anio_vence          smallint,
    guardar_tarjeta     boolean       not null default false,
    metodo_pago_id      bigint references metodo_pago (id) on delete set null,
    estado              varchar(12)   not null,
    autenticacion       varchar(12),
    motivo_fallo        varchar(30),
    perfil_fiscal_id    bigint references perfil_fiscal (id) on delete set null,
    referencia_caja     varchar(40),
    registrado_por      bigint references usuario (id),
    pagado_en           timestamp(6) with time zone,
    creado_en           timestamp(6) with time zone not null default now(),
    actualizado_en      timestamp(6) with time zone not null default now(),
    constraint uq_pago_app_intencion unique (intencion_id),
    constraint uq_pago_app_llave unique (cliente_id, llave_idempotencia),
    constraint ck_pago_app_monto check (monto > 0),
    constraint ck_pago_app_moneda check (moneda = 'MXN'),
    constraint ck_pago_app_estado check (estado in ('PENDIENTE', 'PAGADO', 'FALLIDO', 'REEMBOLSADO')),
    constraint ck_pago_app_metodo check (metodo in ('TARJETA', 'APPLE_PAY', 'GOOGLE_PAY', 'CAJA')),
    constraint ck_pago_app_ultimos4 check (ultimos4 is null or ultimos4 ~ '^[0-9]{4}$'),
    constraint ck_pago_app_vence check ((mes_vence is null) = (anio_vence is null)
        and (mes_vence is null or mes_vence between 1 and 12)),
    constraint ck_pago_app_pagado check (estado <> 'PAGADO' or pagado_en is not null),
    constraint ck_pago_app_fallo check ((estado = 'FALLIDO') = (motivo_fallo is not null)),
    constraint ck_pago_app_llave check (metodo = 'CAJA' or llave_idempotencia is not null)
);

create index ix_pago_app_cliente on pago_app (cliente_id, creado_en desc, id desc);

create index ix_pago_app_orden on pago_app (orden_servicio_id, id);

create unique index uq_pago_app_orden_pagada on pago_app (orden_servicio_id) where estado = 'PAGADO';

create unique index uq_pago_app_orden_pendiente on pago_app (orden_servicio_id) where estado = 'PENDIENTE';

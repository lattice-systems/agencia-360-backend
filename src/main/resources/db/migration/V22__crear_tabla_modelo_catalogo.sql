-- APP-4.1 · Catálogo de vehículos nuevos de la app CareCar.
--
-- Lista aparte del inventario con los modelos actuales (decisión 4 de TEC-1):
-- el inventario son unidades con VIN; el catálogo son modelos para mostrar.
-- Como en el inventario, modelo es el Tipo (Sentra) y anio el Modelo (2026).
-- La versión, el precio desde, la imagen y la descripción son opcionales
-- mientras el PO define qué muestra el catálogo (pregunta 2 de TEC-1). Un
-- modelo que deja de venderse se retira (activo = false), no se borra.
create table modelo_catalogo (
    id           bigint generated by default as identity primary key,
    marca        varchar(40)    not null,
    modelo       varchar(80)    not null,
    anio         integer        not null,
    version      varchar(80),
    precio_desde numeric(12, 2),
    imagen_url   varchar(500),
    descripcion  varchar(500),
    activo       boolean        not null,
    created_at   timestamp(6) with time zone not null,
    updated_at   timestamp(6) with time zone not null,
    constraint ck_modelo_catalogo_anio check (anio >= 1900),
    constraint ck_modelo_catalogo_precio check (precio_desde is null or precio_desde >= 0)
);

create unique index uq_modelo_catalogo on modelo_catalogo (lower(marca), lower(modelo), anio, lower(coalesce(version, '')));

-- V2-M11.01 · Solicitud de asistencia (SOS) del cliente de la app CareCar.
--
-- Columnas de la ficha técnica v2.1. tipo y estado se guardan en mayúsculas; la
-- API los expone en minúsculas. lat y lng viajan juntas o ninguna (el cliente
-- puede negar el permiso de ubicación). Solo puede haber una solicitud abierta
-- (RECIBIDA o EN_CAMINO) por cliente.
create table solicitud_asistencia (
    id                  bigint generated by default as identity primary key,
    cliente_id          bigint        not null,
    vehiculo_cliente_id bigint        not null,
    tipo                varchar(15)   not null,
    lat                 numeric(9, 6),
    lng                 numeric(9, 6),
    comentario          varchar(500),
    estado              varchar(15)   not null,
    creada_en           timestamp(6) with time zone not null,
    constraint fk_solicitud_asistencia_cliente foreign key (cliente_id) references cliente (id),
    constraint fk_solicitud_asistencia_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint ck_solicitud_asistencia_tipo check (tipo in ('LLANTA', 'BATERIA', 'CHOQUE', 'SIN_GASOLINA', 'OTRO')),
    constraint ck_solicitud_asistencia_estado check (estado in ('RECIBIDA', 'EN_CAMINO', 'ATENDIDA', 'CANCELADA')),
    constraint ck_solicitud_asistencia_ubicacion check (
        (lat is null and lng is null)
        or (lat between -90 and 90 and lng between -180 and 180)
    )
);

create unique index uq_solicitud_asistencia_abierta on solicitud_asistencia (cliente_id)
    where estado in ('RECIBIDA', 'EN_CAMINO');

-- Aviso de privacidad versionado y su aceptación por cuenta (V2-M22.01).
--
-- Un aviso publicado nunca se edita: se publica otra versión. La aceptación
-- guarda qué cuenta aceptó qué versión y cuándo, que es lo que cuenta ante una
-- reclamación. La versión vigente es la mayor cuyo vigente_desde ya llegó.

create table aviso_privacidad (
    id            bigint generated by default as identity primary key,
    version       integer      not null,
    texto         text         not null,
    vigente_desde timestamp(6) with time zone not null,
    created_at    timestamp(6) with time zone not null,
    constraint uq_aviso_privacidad_version unique (version),
    constraint ck_aviso_privacidad_version check (version >= 1)
);

create table aceptacion_aviso (
    id                  bigint generated by default as identity primary key,
    cuenta_app_id       bigint       not null,
    aviso_privacidad_id bigint       not null,
    aceptado_en         timestamp(6) with time zone not null,
    constraint fk_aceptacion_aviso_cuenta foreign key (cuenta_app_id) references cuenta_app (id),
    constraint fk_aceptacion_aviso_aviso foreign key (aviso_privacidad_id) references aviso_privacidad (id),
    constraint uq_aceptacion_aviso unique (cuenta_app_id, aviso_privacidad_id)
);

create index idx_aceptacion_aviso_aviso on aceptacion_aviso (aviso_privacidad_id);

-- «Nunca se edita uno publicado»: lo garantiza la base, no solo el servicio.
create function aviso_privacidad_inmutable() returns trigger
    language plpgsql as
$$
begin
    raise exception 'aviso_privacidad es inmutable: publica una versión nueva';
end;
$$;

create trigger trg_aviso_privacidad_inmutable
    before update or delete on aviso_privacidad
    for each row execute function aviso_privacidad_inmutable();


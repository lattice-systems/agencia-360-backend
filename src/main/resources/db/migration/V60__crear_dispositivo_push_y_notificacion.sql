-- V2-M06.02 y V2-M06.07: dispositivos que reciben push y bandeja de avisos.
--
-- Los nombres vienen de la ficha técnica (sección 6): `dispositivo_push` y
-- `notificacion`. Campos de la ficha/plan: token_fcm, plataforma, idioma,
-- actualizado_en, categoria, titulo, cuerpo, destino, leida_en, creada_en.
-- Campos añadidos:
--   * dispositivo_push.instalacion_id: la app genera un UUID por instalación y
--     lo manda en PUT /dispositivos/{instalacionId}; es único, así que una
--     instalación tiene un solo token y volver a registrar lo actualiza.
--   * dispositivo_push.activo: pasa a falso cuando FCM dice que el token ya no
--     existe (app desinstalada); así no se insiste con un token muerto.
--   * dispositivo_push.creado_en.
--   * notificacion.evento y notificacion.datos: el evento de dominio y sus ids
--     (nunca nombres, VIN, placas ni montos), para que la app resuelva el
--     destino y para depurar.
-- `preferencia_notificacion` no va aquí: es de V2-M06.05.
create table dispositivo_push (
    id             bigint generated by default as identity primary key,
    cuenta_app_id  bigint        not null,
    instalacion_id varchar(64)   not null,
    token_fcm      varchar(4096) not null,
    plataforma     varchar(10)   not null,
    idioma         varchar(10)   not null default 'es',
    activo         boolean       not null default true,
    creado_en      timestamp(6) with time zone not null default now(),
    actualizado_en timestamp(6) with time zone not null default now(),
    constraint fk_dispositivo_push_cuenta foreign key (cuenta_app_id) references cuenta_app (id),
    constraint uq_dispositivo_push_instalacion unique (instalacion_id),
    constraint ck_dispositivo_push_plataforma check (plataforma in ('android', 'ios'))
);

-- Un mismo token no puede estar en dos instalaciones. El índice es por el hash
-- porque un token FCM mide unos 160 caracteres pero el campo admite mucho más.
create unique index uq_dispositivo_push_token on dispositivo_push (md5(token_fcm));

create index idx_dispositivo_push_cuenta_activo on dispositivo_push (cuenta_app_id) where activo;

create table notificacion (
    id         bigint generated by default as identity primary key,
    cliente_id bigint       not null,
    categoria  varchar(30)  not null,
    titulo     varchar(120) not null,
    cuerpo     varchar(400) not null,
    destino    varchar(200) not null,
    evento     varchar(60)  not null,
    datos      jsonb        not null default '{}'::jsonb,
    leida_en   timestamp(6) with time zone,
    creada_en  timestamp(6) with time zone not null default now(),
    constraint fk_notificacion_cliente foreign key (cliente_id) references cliente (id),
    constraint ck_notificacion_datos_objeto check (jsonb_typeof(datos) = 'object')
);

-- La bandeja (V2-M06.04) lista por cliente, de la más nueva a la más vieja.
create index idx_notificacion_cliente_creada on notificacion (cliente_id, creada_en desc, id desc);

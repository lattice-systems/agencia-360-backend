-- V2-M10 · Garantía y campañas de seguridad (tablas de la ficha, sección 10).
--
-- garantia: cobertura por componente de un vehículo, con fecha y km límite.
-- Las columnas aviso_* guardan cuándo se avisó que está por vencer (V2-M10.05)
-- para no repetir el aviso.
create table garantia (
    id                  bigint generated by default as identity primary key,
    vehiculo_cliente_id bigint        not null,
    componente          varchar(80)   not null,
    descripcion         varchar(300),
    inicia_en           date          not null,
    vence_en            date          not null,
    km_limite           integer,
    aviso_60_dias_en    timestamp(6) with time zone,
    aviso_15_dias_en    timestamp(6) with time zone,
    aviso_km_en         timestamp(6) with time zone,
    constraint fk_garantia_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint ck_garantia_fechas check (vence_en >= inicia_en),
    constraint ck_garantia_km check (km_limite is null or km_limite > 0)
);

create index ix_garantia_vehiculo on garantia (vehiculo_cliente_id);

-- campana_seguridad: recall del fabricante. Aplica a un modelo (Tipo, sin
-- distinguir mayúsculas) entre dos años y, si se da, a un rango de VIN.
create table campana_seguridad (
    id           bigint generated by default as identity primary key,
    codigo       varchar(30)   not null,
    titulo       varchar(120)  not null,
    descripcion  varchar(1000) not null,
    que_hacer    varchar(500)  not null,
    gravedad     varchar(10)   not null,
    modelo       varchar(60)   not null,
    anio_desde   integer       not null,
    anio_hasta   integer       not null,
    vin_desde    varchar(17),
    vin_hasta    varchar(17),
    publicada_en timestamp(6) with time zone not null,
    constraint uq_campana_seguridad_codigo unique (codigo),
    constraint ck_campana_seguridad_gravedad check (gravedad in ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    constraint ck_campana_seguridad_anios check (anio_hasta >= anio_desde),
    constraint ck_campana_seguridad_vin check ((vin_desde is null and vin_hasta is null)
        or (vin_desde is not null and vin_hasta is not null and vin_hasta >= vin_desde))
);

-- campana_vehiculo: la campaña para un vehículo que entra en su cruce. Al
-- agendar guarda la cita (V2-M10.03).
create table campana_vehiculo (
    id                   bigint generated by default as identity primary key,
    campana_seguridad_id bigint      not null,
    vehiculo_cliente_id  bigint      not null,
    estado               varchar(10) not null,
    cita_id              bigint,
    avisada_en           timestamp(6) with time zone,
    constraint fk_campana_vehiculo_campana foreign key (campana_seguridad_id) references campana_seguridad (id),
    constraint fk_campana_vehiculo_vehiculo foreign key (vehiculo_cliente_id) references vehiculo_cliente (id),
    constraint fk_campana_vehiculo_cita foreign key (cita_id) references cita (id),
    constraint uq_campana_vehiculo unique (campana_seguridad_id, vehiculo_cliente_id),
    constraint ck_campana_vehiculo_estado check (estado in ('ABIERTA', 'AGENDADA', 'ATENDIDA')),
    constraint ck_campana_vehiculo_cita check (estado <> 'AGENDADA' or cita_id is not null)
);

create index ix_campana_vehiculo_vehiculo on campana_vehiculo (vehiculo_cliente_id);

-- Una cita puede ser para atender una campaña (motivo CAMPANA).
alter table cita drop constraint ck_cita_motivo;
alter table cita add constraint ck_cita_motivo
    check (motivo is null or motivo in ('MANTENIMIENTO', 'REPARACION', 'REVISION', 'GARANTIA', 'CAMPANA', 'OTRO'));

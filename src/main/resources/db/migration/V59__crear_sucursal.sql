-- V2-M27.02: sucursales de la agencia con su ubicación y sus horarios.
--
-- Los nombres vienen de la ficha técnica (sección 23): `lat` y `lng`, no
-- latitud y longitud; la API sí habla en `latitud` y `longitud`. `activa` y
-- `orden` son campos añadidos para retirar una sucursal sin borrarla y para
-- decidir cuál va primero (la app usa la primera como la principal).
--
-- `horarios` es una lista de {departamento, dias, abre, cierra}: dias ISO
-- (1 lunes a 7 domingo) y horas HH:mm en la hora de la agencia. Se valida al
-- leerse (HorarioSucursal); la base solo exige que sea una lista.
create table sucursal (
    id         bigint generated by default as identity primary key,
    nombre     varchar(80)   not null,
    direccion  varchar(200)  not null,
    lat        numeric(9, 6) not null,
    lng        numeric(9, 6) not null,
    telefono   varchar(30),
    correo     varchar(120),
    horarios   jsonb         not null default '[]'::jsonb,
    activa     boolean       not null default true,
    orden      integer       not null default 0,
    created_at timestamp(6) with time zone not null default now(),
    updated_at timestamp(6) with time zone not null default now(),
    constraint ck_sucursal_lat check (lat between -90 and 90),
    constraint ck_sucursal_lng check (lng between -180 and 180),
    constraint ck_sucursal_horarios_lista check (jsonb_typeof(horarios) = 'array')
);

create index idx_sucursal_activa_orden on sucursal (activa, orden, id);


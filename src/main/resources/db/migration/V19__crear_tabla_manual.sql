-- APP-3.1 · Manuales de los vehículos en la app CareCar.
--
-- Un manual es de una marca, un tipo y un modelo (por ejemplo, Nissan March
-- 2026): la versión no cambia el manual. Su nombre se arma con esos datos
-- ("Nissan March 2026 Manual de propietario"). Solo PDF, de 20 MB como máximo.
--
-- El archivo no se guarda en la base: archivo es la clave con la que lo
-- encuentra el almacenamiento (en desarrollo, una carpeta local; después, Azure
-- Blob Storage). Lo sube el Gerente de marketing.

create table manual (
    id           bigint generated by default as identity primary key,
    marca        varchar(40)  not null,
    modelo       varchar(80)  not null,
    anio         integer      not null,
    archivo      varchar(200) not null,
    tamano_bytes bigint       not null,
    subido_por   bigint       not null,
    created_at   timestamp(6) with time zone not null,
    updated_at   timestamp(6) with time zone not null,
    constraint fk_manual_subido_por foreign key (subido_por) references usuario (id),
    constraint uq_manual_archivo unique (archivo),
    constraint ck_manual_anio check (anio >= 1900),
    constraint ck_manual_tamano check (tamano_bytes > 0 and tamano_bytes <= 20971520)
);

-- Un solo manual por marca, tipo y modelo, sin distinguir mayúsculas.
create unique index uq_manual_vehiculo on manual (lower(marca), lower(modelo), anio);
